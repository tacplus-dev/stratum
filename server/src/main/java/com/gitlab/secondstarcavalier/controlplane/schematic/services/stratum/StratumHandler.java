/**
 * StratumHandler wires together EventStore and the generated record query plane.
 *
 * Startup sequence:
 *   1. provideRecordPlane() — lazily initialises EventStore (hot event
 *      Hazelcast cluster) from config defaults, then returns
 *      StratumRecordMaps for registration on both caller surfaces.
 *   2. handleConfig() — re-applies config when kernel delivers it.
 *   3. onEventStream() begins receiving records from the EventBus, storing them.
 *
 * EventBus subscription is auto-generated by tacplus from (spec.hot_store).
 */
public class StratumHandler extends StratumVServiceBase {

    private static final Logger log = LoggerFactory.getLogger(StratumHandler.class);

    private final ServiceManager sm;
    private volatile Stratum.Config config;
    // volatile: the record plane reads this field from gRPC threads on every call
    // (see provideRecordPlane's suppliers), while initFromConfig replaces it. The
    // restore gate below is only meaningful if a reader sees the CURRENT store —
    // observing the previous one would report the new store's restore as finished.
    private volatile EventStore eventStore;
    /**
     * Whether the event-log cold-start replay has actually FINISHED, as opposed to
     * having been started once. It replaces a "handled" latch that was raised the
     * moment the replay was kicked off: that could not gate reads, because the
     * whole point is the window between kickoff and catch-up, and it also made a
     * reload that shut down an in-flight replay decline to ever run another one.
     */
    private volatile boolean coldStartComplete;
    private volatile ColdStartRebuilder coldStartRebuilder;
    private StratumRecordMaps recordMaps;


    public StratumHandler(ServiceManager sm) {
        this.sm = sm;
    }

    // -----------------------------------------------------------------------
    // StratumVServiceBase — vservice wiring
    // -----------------------------------------------------------------------

    /**
     * The one query-plane implementation, shared by both caller surfaces.
     * Created once: the handle registry lives in the instance, so returning a
     * fresh one per surface would give each surface its own set of query ids.
     *
     * StratumVServiceBase binds this to the plane's two generated services. The
     * plane's service names come off the (spec.trait) declaration that produced
     * it, so nothing here may name them.
     */
    @Override
    protected synchronized StratumRecordMaps provideRecordPlane() {
        try {
            if (eventStore == null) {
                initFromConfig(Helpers.configDefaults(Stratum.Config.getDefaultInstance()).build());
            }
        } catch (Exception e) {
            log.error("failed to initialize stratum", e);
            throw new RuntimeException("stratum init failed", e);
        }
        if (recordMaps == null) {
            // Suppliers, not captured references: initFromConfig rebuilds the stores on
            // config updates, and the generated impl must always see the current ones.
            recordMaps = new StratumRecordMaps(() -> eventStore.stores(), () -> eventStore.warm(),
                    // The hot tier's restore gate. It is not always true by the time a
                    // read arrives: initFromConfig replaces the EventStore on every
                    // config delivery, and the plane stays registered across that, so a
                    // read landing during a reload sees a store that is null or still
                    // replaying its redo logs. Both answer "not readable".
                    () -> {
                        EventStore store = eventStore;
                        return store != null && store.hotReadable();
                    });
        }
        return recordMaps;
    }

    @Override
    protected void handleConfig(Stratum.Config cfg) throws Exception {
        initFromConfig(cfg);
    }

    @Override
    public void handleStratumConfigStateConfig(Stratum.Config cfg) throws Exception {
        initFromConfig(cfg);
    }

    @Override
    public void handleStratumStateConfig(Stratum.Config cfg) throws Exception {
        // StratumState has no config singleton; nothing to do.
    }

    @Override
    public com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum.model.s2sm.internal.grpc.servers.services.stratum.StratumStateService.StratumStateServiceHandler getStratumStateGrpcImpl() {
        return new com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum.model.s2sm.internal.grpc.servers.services.stratum.StratumStateService.StratumStateServiceHandler() {};
    }

    @Override
    public com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum.model.s2sm.internal.grpc.servers.services.stratum.StratumConfigStateService.StratumConfigStateServiceHandler getStratumConfigStateGrpcImpl() {
        return new com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum.model.s2sm.internal.grpc.servers.services.stratum.StratumConfigStateService.StratumConfigStateServiceHandler() {
            @Override
            public Stratum.Config getConfig(Caller caller) throws ProtoException {
                Stratum.Config cfg = config;
                return cfg != null ? cfg : Stratum.Config.getDefaultInstance();
            }
            @Override
            public Stratum.Config setConfig(Caller caller, Stratum.Config request) throws ProtoException {
                try {
                    initFromConfig(request);
                } catch (Exception e) {
                    throw new ProtoException(ProtoException.INTERNAL, e.getMessage());
                }
                return request;
            }
            @Override
            public void watchConfig(Caller caller, StreamObserver<Stratum.Config> responseObserver) throws ProtoException {
                Stratum.Config cfg = config;
                if (cfg != null) responseObserver.onNext(cfg);
                responseObserver.onCompleted();
            }
        };
    }

    /**
     * Hazelcast seed members for the event store, from STRATUM_SEED_MEMBERS.
     *
     * The operator renders one "stratum0-<i>.stratum0:5001" entry per replica
     * from the StatefulSet's stable per-pod DNS. Peer topology is deployment
     * shape the operator already knows, wired the same way graphdb gets
     * GRAPHDB_ZERO_ADDR.
     *
     * Empty (a plain local run) falls back to multicast. That is fine on a
     * laptop and useless in Kubernetes, where it would leave every replica in
     * its own cluster of one — each seeing an empty store, each concluding it
     * was a cold boot, and each replaying the entire event log.
     */
    private static List<String> seedMembers() {
        String raw = System.getenv("STRATUM_SEED_MEMBERS");
        if (raw == null || raw.isBlank()) {
            log.info("STRATUM_SEED_MEMBERS unset — Hazelcast will use multicast (single-node/dev)");
            return List.of();
        }
        List<String> members = Arrays.stream(raw.split(","))
                .map(String::trim)
                .filter(m -> !m.isEmpty())
                .toList();
        log.info("Hazelcast seed members: {}", members);
        return members;
    }

    private void initFromConfig(Stratum.Config cfg) {
        // Nothing to do when the config has not actually changed.
        //
        // This method is reachable from SIX places: the initial config, the
        // handleConfig hot-reload, the plane's config handlers, two lazy-init
        // fallbacks and a request path. Every one of them used to build a new
        // EventStore, and that calls
        // Hazelcast.newHazelcastInstance -- so a repeated config delivery left
        // the previous members RUNNING. Observed live: "EventStore initialised"
        // three times in one pod, giving three Hazelcast members
        // (stratum-events x3) on ports 5701-5703.
        //
        // That is not just wasted heap and threads. The orphans JOIN the same
        // cluster -- Hazelcast reported Members{size:3} -- so partitions
        // rebalance across members nobody holds a reference to, while the
        // eventStore field points only at the newest. Reads and writes can land
        // on different owners, which is exactly the "stored it, cannot read it
        // back" behaviour that took three rounds to chase down.
        if (this.config != null && this.config.equals(cfg) && eventStore != null) {
            log.info("config unchanged — keeping the existing stores");
            return;
        }

        // Replacing the stores means disposing of the old ones FIRST. Hazelcast
        // members do not go away because the reference did.
        if (coldStartRebuilder != null) {
            try { coldStartRebuilder.shutdown(); } catch (Exception e) { log.warn("rebuilder shutdown: {}", e.getMessage()); }
            coldStartRebuilder = null;
        }
        if (eventStore != null) {
            log.info("re-initialising: shutting down the previous EventStore");
            try { eventStore.shutdown(); } catch (Exception e) { log.warn("EventStore shutdown: {}", e.getMessage()); }
            eventStore = null;
        }
        this.config = cfg;
        log.info("config: hazelcast_memory_mb={}, map_idle_ttl_seconds={}, max_maps={}, " +
                 "retention_days={}, cleanup_interval_seconds={}",
                cfg.getHazelcastMemoryMb(), cfg.getMapIdleTtlSeconds(), cfg.getMaxMaps(),
                cfg.getRetentionDays(), cfg.getCleanupIntervalSeconds());

        eventStore = new EventStore();
        eventStore.init(
                cfg.getRetentionDays(),
                cfg.getCleanupIntervalSeconds(),
                seedMembers());

        // Startup replay, but ONLY on a cold boot — see
        // ColdStartRebuilder.shouldReplay. With peers in the cluster a
        // restarting member gets its partitions back from them, which is the
        // common case in production and must not pull the whole event log
        // through the broker. Replay is idempotent (IMap put = upsert keyed by
        // event_id), so when it does run a partially-surviving store still
        // converges.
        //
        // Whichever branch is taken, it ENDS by telling the store where the
        // cold-start leg of the read gate stands. The gate is closed until it is
        // told, so a branch that says nothing leaves reads refused forever.
        EventStore store = eventStore;
        if (coldStartComplete) {
            // A config reload after the replay already finished. The data it
            // recovered is in the shared cluster map, which this new store is a
            // member of, so its gate opens on the redo barrier alone.
            store.coldStartReplayComplete();
        } else {
            long held = store.eventCount();
            int members = store.clusterSize();
            if (ColdStartRebuilder.shouldReplay(held)) {
                log.info("cold boot: store is empty cluster-wide ({} member(s)) — replaying the event log",
                        members);
                coldStartRebuilder = new ColdStartRebuilder();
                coldStartRebuilder.startReplay(sm, this, () -> onColdStartComplete(store));
            } else {
                log.info("warm start: {} records held, {} cluster member(s) — skipping event-log replay",
                        held, members);
                onColdStartComplete(store);
            }
        }
    }

    /**
     * The cold-start leg of the read gate, opened for the store the replay was
     * started for.
     *
     * <p>Bound to that specific store rather than to whatever {@code eventStore}
     * happens to hold: a reload replaces the store and shuts the old rebuild down,
     * and a callback from that dying rebuild arriving afterwards must not open the
     * NEW store's gate on the old store's work. The handler-level flag is only
     * raised when the two still match, so a reload that interrupted an incomplete
     * replay re-runs the cold-start decision above rather than inheriting a
     * completion that never happened.
     */
    private void onColdStartComplete(EventStore store) {
        store.coldStartReplayComplete();
        if (eventStore == store) {
            coldStartComplete = true;
        }
    }

    @Override
    public void newTlsCert(X509.X509CertChain certChain, byte[] privateKeyDer) throws Exception {
        // mTLS for EventBus subscription is handled by the generated ServiceManager.
    }

    // -----------------------------------------------------------------------
    // EventBus subscription (auto-wired by (spec.hot_store))
    // -----------------------------------------------------------------------

    /**
     * Single, vservice-neutral ingest path. The model-generated Handler routes
     * every typed onEventStream* topic here by default, so we do NOT override
     * the per-vservice methods. Each event is stored via the generated typed
     * store — adding or removing a vservice (or .off-ing its proto) needs no
     * change here.
     */
    @Override
    public void handleEventStreamMessage(String topic, com.google.protobuf.Message event, SubscriptionMeta meta) throws Exception {
        if (!eventStore.store(event)) {
            log.warn("unhandled event stream topic: {} (offset={})", topic, meta.offset);
        }
    }


    @Override
    public void shutdown() {
        log.info("stratum shutting down");
        ColdStartRebuilder rebuilder = coldStartRebuilder;
        if (rebuilder != null) rebuilder.shutdown();
        if (eventStore != null) eventStore.shutdown();
    }


    // -----------------------------------------------------------------------
    // Pagination helpers
    // -----------------------------------------------------------------------

    static String i64Key(long value) {
        return String.format("%020d", Math.max(0L, value));
    }

    private static int compareKeys(List<String> left, List<String> right) {
        int n = Math.min(left.size(), right.size());
        for (int i = 0; i < n; i++) {
            int cmp = left.get(i).compareTo(right.get(i));
            if (cmp != 0) return cmp;
        }
        return Integer.compare(left.size(), right.size());
    }

    // Package-private: reused by the generated StratumRecordMaps (RecordMap.list<T>).
    static <T> CollectionRuntime.Page<T> pageSorted(
            List<T> all,
            CollectionRuntime.PageParams page,
            Function<T, List<String>> keyFor) {
        all.sort((a, b) -> compareKeys(keyFor.apply(a), keyFor.apply(b)));
        int limit = (int) Math.max(1L, page.limit);
        int start = 0;
        if (page.after != null && page.after.keys != null) {
            while (start < all.size() && compareKeys(keyFor.apply(all.get(start)), page.after.keys) <= 0) {
                start++;
            }
        }
        int end = Math.min(start + limit, all.size());
        List<T> items = new ArrayList<>(all.subList(start, end));
        CollectionRuntime.Cursor nextAfter = end < all.size() && !items.isEmpty()
                ? new CollectionRuntime.Cursor(keyFor.apply(items.get(items.size() - 1)))
                : null;
        return new CollectionRuntime.Page<>(items, nextAfter, all.size());
    }
}
