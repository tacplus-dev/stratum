/**
 * StratumHandler wires together EventStore, WorkingSetStore, the generated
 * vservice-neutral RecordMap service, and the StratumQuery vservice (session
 * queries + map-plane RPCs for argus).
 *
 * Startup sequence:
 *   1. getRecordMapGrpcImpl() — lazily initialises EventStore (hot event
 *      Hazelcast cluster) and WorkingSetStore (working-set Hazelcast cluster)
 *      from config defaults, then returns StratumRecordMaps for registration.
 *   2. provideStratumQueryHandler() — returns StratumQueryImpl backed by
 *      the same EventStore + WorkingSetStore via suppliers.
 *   3. handleConfig() — re-applies config when kernel delivers it.
 *   4. onEventStream() begins receiving records from the EventBus, storing
 *      them and pushing live session updates to StratumQueryImpl watchers.
 *
 * EventBus subscription is auto-generated by tacplus from (spec.hot_store).
 */
public class StratumHandler extends StratumVServiceBase {

    private static final Logger log = LoggerFactory.getLogger(StratumHandler.class);

    private final ServiceManager sm;
    private volatile Stratum.Config config;
    private EventStore      eventStore;
    private WorkingSetStore store;
    private volatile StratumQueryImpl queryImpl;
    private final AtomicBoolean coldStartHandled = new AtomicBoolean(false);
    private volatile ColdStartRebuilder coldStartRebuilder;


    public StratumHandler(ServiceManager sm) {
        this.sm = sm;
    }

    // -----------------------------------------------------------------------
    // StratumVServiceBase — vservice wiring
    // -----------------------------------------------------------------------

    @Override
    public com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum.model.s2sm.internal.grpc.servers.services.stratum.RecordMap.RecordMapHandler getRecordMapGrpcImpl() {
        try {
            if (store == null || eventStore == null) {
                initFromConfig(Helpers.configDefaults(Stratum.Config.getDefaultInstance()).build());
            }
        } catch (Exception e) {
            log.error("failed to initialize stratum", e);
            throw new RuntimeException("stratum init failed", e);
        }
        // Suppliers, not captured references: initFromConfig rebuilds the stores on
        // config updates, and the generated impl must always see the current ones.
        return new StratumRecordMaps(() -> eventStore.stores());
    }

    @Override
    public void handleRecordMapConfig(Stratum.Config cfg) throws Exception {
        initFromConfig(cfg);
    }

    @Override
    protected void handleConfig(Stratum.Config cfg) throws Exception {
        initFromConfig(cfg);
    }

    @Override
    protected StratumQuery.StratumQueryHandler provideStratumQueryHandler() {
        try {
            if (store == null || eventStore == null) {
                initFromConfig(Helpers.configDefaults(Stratum.Config.getDefaultInstance()).build());
            }
        } catch (Exception e) {
            log.error("failed to initialize stratum", e);
            throw new RuntimeException("stratum init failed", e);
        }
        queryImpl = new StratumQueryImpl(
                () -> eventStore, () -> store, () -> config);
        return queryImpl;
    }

    @Override
    public void handleStratumConfigStateConfig(Stratum.Config cfg) throws Exception {
        initFromConfig(cfg);
    }

    @Override
    public void handleStratumStateConfig(Stratum.Config cfg) throws Exception {
        // StratumState has no config singleton; nothing to do.
    }

    @Override
    public com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum.model.s2sm.internal.grpc.servers.services.stratum.StratumStateService.StratumStateServiceHandler getStratumStateGrpcImpl() {
        return new com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum.model.s2sm.internal.grpc.servers.services.stratum.StratumStateService.StratumStateServiceHandler() {};
    }

    @Override
    public com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum.model.s2sm.internal.grpc.servers.services.stratum.StratumConfigStateService.StratumConfigStateServiceHandler getStratumConfigStateGrpcImpl() {
        return new com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum.model.s2sm.internal.grpc.servers.services.stratum.StratumConfigStateService.StratumConfigStateServiceHandler() {
            @Override
            public Stratum.Config getConfig(Caller caller) throws ProtoException {
                Stratum.Config cfg = config;
                return cfg != null ? cfg : Stratum.Config.getDefaultInstance();
            }
            @Override
            public Stratum.Config setConfig(Caller caller, Stratum.Config request) throws ProtoException {
                try {
                    initFromConfig(request);
                } catch (Exception e) {
                    throw new ProtoException(ProtoException.INTERNAL, e.getMessage());
                }
                return request;
            }
            @Override
            public void watchConfig(Caller caller, StreamObserver<Stratum.Config> responseObserver) throws ProtoException {
                Stratum.Config cfg = config;
                if (cfg != null) responseObserver.onNext(cfg);
                responseObserver.onCompleted();
            }
        };
    }

    private void initFromConfig(Stratum.Config cfg) {
        this.config = cfg;
        log.info("config: hazelcast_memory_mb={}, map_idle_ttl_seconds={}, max_maps={}, " +
                 "retention_days={}, cleanup_interval_seconds={}",
                cfg.getHazelcastMemoryMb(), cfg.getMapIdleTtlSeconds(), cfg.getMaxMaps(),
                cfg.getRetentionDays(), cfg.getCleanupIntervalSeconds());

        eventStore = new EventStore();
        eventStore.init(
                cfg.getRetentionDays(),
                cfg.getCleanupIntervalSeconds(),
                List.of()); // seed members: empty = single-node / multicast

        store = new WorkingSetStore(cfg);
        store.init();

        // Startup replay: replay all events from eventbus at offset 0 once per
        // process lifetime. Idempotent (IMap put = upsert keyed by event_id), so
        // a partially-surviving store converges to the full set from the log.
        if (coldStartHandled.compareAndSet(false, true)) {
            log.info("startup: store holds {} records before replay", eventStore.stores().totalCount());
            coldStartRebuilder = new ColdStartRebuilder();
            coldStartRebuilder.startReplay(sm, this);
        }
    }

    @Override
    public void newTlsCert(X509.X509CertChain certChain, byte[] privateKeyDer) throws Exception {
        // mTLS for EventBus subscription is handled by the generated ServiceManager.
    }

    // -----------------------------------------------------------------------
    // EventBus subscription (auto-wired by (spec.hot_store))
    // -----------------------------------------------------------------------

    /**
     * Single, vservice-neutral ingest path. The model-generated Handler routes
     * every typed onEventStream* topic here by default, so we do NOT override
     * the per-vservice methods. Each event is stored via the generated typed
     * store — adding or removing a vservice (or .off-ing its proto) needs no
     * change here.
     */
    @Override
    public void handleEventStreamMessage(String topic, com.google.protobuf.Message event, SubscriptionMeta meta) throws Exception {
        if (!eventStore.store(event)) {
            log.warn("unhandled event stream topic: {} (offset={})", topic, meta.offset);
            return;
        }
        // Live session fan-out for subscribeLiveSessions watchers.
        StratumQueryImpl qi = queryImpl;
        if (qi != null && event instanceof Agentsensor.AgentEvent) {
            qi.onEvent((Agentsensor.AgentEvent) event);
        }
    }


    @Override
    public void shutdown() {
        log.info("stratum shutting down");
        ColdStartRebuilder rebuilder = coldStartRebuilder;
        if (rebuilder != null) rebuilder.shutdown();
        if (eventStore != null) eventStore.shutdown();
        if (store != null)      store.shutdown();
    }


    // -----------------------------------------------------------------------
    // Pagination helpers
    // -----------------------------------------------------------------------

    static String i64Key(long value) {
        return String.format("%020d", Math.max(0L, value));
    }

    private static int compareKeys(List<String> left, List<String> right) {
        int n = Math.min(left.size(), right.size());
        for (int i = 0; i < n; i++) {
            int cmp = left.get(i).compareTo(right.get(i));
            if (cmp != 0) return cmp;
        }
        return Integer.compare(left.size(), right.size());
    }

    // Package-private: reused by the generated StratumRecordMaps (RecordMap.list<T>).
    static <T> CollectionRuntime.Page<T> pageSorted(
            List<T> all,
            CollectionRuntime.PageParams page,
            Function<T, List<String>> keyFor) {
        all.sort((a, b) -> compareKeys(keyFor.apply(a), keyFor.apply(b)));
        int limit = (int) Math.max(1L, page.limit);
        int start = 0;
        if (page.after != null && page.after.keys != null) {
            while (start < all.size() && compareKeys(keyFor.apply(all.get(start)), page.after.keys) <= 0) {
                start++;
            }
        }
        int end = Math.min(start + limit, all.size());
        List<T> items = new ArrayList<>(all.subList(start, end));
        CollectionRuntime.Cursor nextAfter = end < all.size() && !items.isEmpty()
                ? new CollectionRuntime.Cursor(keyFor.apply(items.get(items.size() - 1)))
                : null;
        return new CollectionRuntime.Page<>(items, nextAfter, all.size());
    }
}
