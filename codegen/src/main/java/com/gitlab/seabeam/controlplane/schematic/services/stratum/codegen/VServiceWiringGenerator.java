package com.gitlab.seabeam.controlplane.schematic.services.stratum.codegen;

import java.io.IOException;
import java.io.PrintWriter;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/**
 * Generates StratumVServiceBase.java — an abstract base class that bridges the
 * model-generated Handler interface to stratum's vservice implementations and to
 * the generated record query plane.
 *
 * For each discovered hosted vservice (e.g. StratumQuery), the generated class:
 *   1. Implements get{ServiceName}GrpcImpl() by delegating to provide{ServiceName}Handler()
 *   2. Implements handle{ServiceName}Config(Stratum.Config) by delegating to handleConfig()
 *   3. Declares abstract methods provide{ServiceName}Handler() and handleConfig()
 *
 * StratumHandler extends this generated base class and only needs to implement
 * the abstract methods for each hosted vservice.
 *
 * When a new vservice is added with {label: "stratum"}, the codegen automatically
 * adds the corresponding abstract methods — stratum never needs manual wiring.
 */
public class VServiceWiringGenerator {

    private static final String HOST_PKG_BASE = "com.gitlab.seabeam.controlplane.schematic.services.stratum";
    private static final String MODEL_BASE = HOST_PKG_BASE + ".model";
    private static final String SM_PREFIX = "s2sm";

    /**
     * Generates StratumVServiceBase.java into the given output directory.
     *
     * @param outputDir  root source output directory
     * @param services   discovered vservices with {label: "stratum"}
     * @param plane      the discovered record query plane, or null when the
     *                   proto set declares none
     */
    public static void generate(Path outputDir, List<VServiceDiscovery.HostedVService> services,
                                VServiceDiscovery.RecordPlane plane)
            throws IOException {
        String pkg = HOST_PKG_BASE;
        Path pkgDir = outputDir.resolve(pkg.replace('.', '/'));
        Files.createDirectories(pkgDir);

        Path outFile = pkgDir.resolve("StratumVServiceBase.java");
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(outFile))) {
            writeFile(w, pkg, services, plane);
        }
    }

    private static void writeFile(PrintWriter w, String pkg,
                                   List<VServiceDiscovery.HostedVService> services,
                                   VServiceDiscovery.RecordPlane plane) {
        w.println("// Copyright (c) 2026 Seabeam LLC. All rights reserved.");
        w.println("// GENERATED by stratum-codegen — do not edit.");
        w.println("// Source: services labelled {label: \"stratum\"} plus the record query plane.");
        w.println();
        w.println("package " + pkg + ";");
        w.println();

        // Imports
        w.println("import " + MODEL_BASE + "." + SM_PREFIX + ".Handler;");
        w.println("import " + MODEL_BASE + ".types.services.stratum.Stratum;");
        for (VServiceDiscovery.HostedVService svc : services) {
            w.println("import " + svc.wrapperFqn(MODEL_BASE, SM_PREFIX) + ";");
        }
        if (plane != null) {
            w.println("import " + plane.s2s.wrapperFqn(MODEL_BASE, SM_PREFIX) + ";");
            if (plane.c2s != null) {
                w.println("import " + plane.c2s.wrapperFqn(MODEL_BASE, SM_PREFIX) + ";");
            }
        }
        w.println();

        w.println("/**");
        w.println(" * StratumVServiceBase wires model-generated Handler interface methods");
        w.println(" * to stratum's vservice implementation providers.");
        w.println(" *");
        w.println(" * Discovered hosted vservices (label: \"stratum\"):");
        for (VServiceDiscovery.HostedVService svc : services) {
            w.println(" *   - " + svc.protoPackage + "." + svc.serviceName +
                    " (" + svc.protoRelPath + ")");
        }
        w.println(" *");
        w.println(" * Extend this class and implement each provide*Handler() method.");
        w.println(" * When a new vservice is added with {label: \"stratum\"}, this class");
        w.println(" * is regenerated automatically — no manual wiring needed.");
        w.println(" */");
        w.println("public abstract class StratumVServiceBase implements Handler {");
        w.println();

        for (VServiceDiscovery.HostedVService svc : services) {
            String handlerType = svc.serviceName + "." + svc.serviceName + "Handler";
            String getterName = "get" + svc.serviceName + "GrpcImpl";
            String providerName = "provide" + svc.serviceName + "Handler";
            String configHandlerName = "handle" + svc.serviceName + "Config";

            w.println("    // --- " + svc.serviceName + " (" + svc.protoPackage + ") ---");
            w.println();

            // getXxxGrpcImpl() implementation
            w.println("    @Override");
            w.println("    public final " + handlerType + " " + getterName + "() {");
            w.println("        return " + providerName + "();");
            w.println("    }");
            w.println();

            // handleXxxConfig() — vservices share stratum's config
            w.println("    @Override");
            w.println("    public void " + configHandlerName + "(Stratum.Config cfg) throws Exception {");
            w.println("        handleConfig(cfg);");
            w.println("    }");
            w.println();

            // Abstract provider method
            w.println("    /**");
            w.println("     * Returns the " + svc.serviceName + " handler implementation.");
            w.println("     * Called once at startup by the generated ServiceManager.");
            w.println("     */");
            w.println("    protected abstract " + handlerType + " " + providerName + "();");
            w.println();
        }

        if (plane != null) {
            writeRecordPlane(w, plane);
        }

        // Abstract handleConfig — called by all vservice config handlers
        w.println("    /**");
        w.println("     * Called when stratum config is updated.");
        w.println("     * All hosted vservice config handlers delegate here.");
        w.println("     */");
        w.println("    protected abstract void handleConfig(Stratum.Config cfg) throws Exception;");
        w.println("}");
    }

    /**
     * Wires the record query plane's two sibling services.
     *
     * Unlike a hand-written vservice these are implemented by generated code —
     * StratumRecordMaps (s2s) and StratumRecordQueries (c2s) — so the base binds
     * them here rather than declaring a provider per service name. That is what
     * keeps StratumHandler from naming them: the plane's service names come off
     * the declaration that produced it, and a hand-written override would have to
     * be re-edited every time that declaration changed.
     *
     * Both surfaces share ONE StratumRecordMaps instance: the handle registry
     * lives in it, so a second instance would give each surface its own set of
     * query ids.
     */
    private static void writeRecordPlane(PrintWriter w, VServiceDiscovery.RecordPlane plane) {
        String s2s = plane.s2s.serviceName;

        w.println("    // --- record query plane (" + plane.s2s.protoRelPath + ") ---");
        w.println();
        w.println("    @Override");
        w.println("    public final " + s2s + "." + s2s + "Handler get" + s2s + "GrpcImpl() {");
        w.println("        return provideRecordPlane();");
        w.println("    }");
        w.println();
        w.println("    @Override");
        w.println("    public void handle" + s2s + "Config(Stratum.Config cfg) throws Exception {");
        w.println("        handleConfig(cfg);");
        w.println("    }");
        w.println();

        if (plane.c2s != null) {
            String c2s = plane.c2s.serviceName;
            w.println("    @Override");
            w.println("    public final " + c2s + "." + c2s + "Handler get" + c2s + "GrpcImpl() {");
            w.println("        return new StratumRecordQueries(provideRecordPlane());");
            w.println("    }");
            w.println();
            w.println("    @Override");
            w.println("    public void handle" + c2s + "Config(Stratum.Config cfg) throws Exception {");
            w.println("        handleConfig(cfg);");
            w.println("    }");
            w.println();
        }

        w.println("    /**");
        w.println("     * The one query-plane implementation, shared by both surfaces.");
        w.println("     */");
        w.println("    protected abstract StratumRecordMaps provideRecordPlane();");
        w.println();
    }
}
