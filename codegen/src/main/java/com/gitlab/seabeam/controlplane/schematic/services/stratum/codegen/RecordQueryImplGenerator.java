package com.gitlab.seabeam.controlplane.schematic.services.stratum.codegen;

import java.io.IOException;
import java.io.PrintWriter;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/**
 * Generates StratumRecordQueries.java — the implementation of the C2S half of
 * the generated record query plane.
 *
 * tacplus emits the plane twice because a service declares exactly one caller
 * surface: the trait's s2s_service (reached by a peer) and its c2s_service
 * (reached with a user token through the gateway). Same messages, same handles,
 * same lifecycle — only the RPC vocabulary differs, because a c2s method has to
 * classify against the closed verb registry:
 *
 *   create&lt;T&gt;Query    → open&lt;T&gt;Query
 *   update&lt;T&gt;Query    → refine&lt;T&gt;
 *   get&lt;T&gt;Count       → count&lt;T&gt;
 *   get&lt;T&gt;Sample      → sample&lt;T&gt;
 *   list&lt;T&gt;           → pull&lt;T&gt;
 *   delete&lt;T&gt;Query    → close&lt;T&gt;
 *   watch&lt;T&gt;          → watch&lt;T&gt;
 *   subscribe&lt;T&gt;Count → subscribe&lt;T&gt;Count
 *
 * So this class is a pure delegation shim onto StratumRecordQueries' s2s twin.
 * It is NOT a second implementation: it holds the same StratumRecordMaps
 * instance, so both surfaces share ONE handle registry and one store view. A
 * handle is an opaque UUID a caller only ever gets back from its own
 * create/open call, so sharing the registry grants nothing across surfaces —
 * it is what makes "one query lifecycle, two doors" true rather than aspirational.
 *
 * Row filtering (which records a c2s caller may SEE, as opposed to which fields
 * egress raw) is deliberately absent and belongs at create&lt;T&gt;Query, the
 * lifecycle's single entry point — see the tacplus record_map.go surface comment.
 */
public final class RecordQueryImplGenerator {

    static final String HOST_PKG =
            "com.gitlab.seabeam.controlplane.schematic.services.stratum";
    private static final String MODEL_BASE = HOST_PKG + ".model";
    private static final String SM_PREFIX = "s2sm";
    private static final String CALLER = MODEL_BASE + ".chassis.servicemanager.Caller";
    private static final String PROTO_EXCEPTION = MODEL_BASE + ".types.sys.errors.ProtoException";
    private static final String COLLECTION_RUNTIME = MODEL_BASE + ".chassis.collection.CollectionRuntime";
    static final String CLASS_NAME = "StratumRecordQueries";

    private RecordQueryImplGenerator() {}

    /**
     * @param plane   the C2S half of the discovered record query plane; its
     *                service name and message outer class are read off the
     *                declaration that produced the plane, not fixed here
     * @param records the record types the plane serves
     */
    public static void generate(Path outputDir, VServiceDiscovery.HostedVService plane,
                                List<EventTopicDiscovery.TopicEvent> records)
            throws IOException {
        Path pkgDir = outputDir.resolve(HOST_PKG.replace('.', '/'));
        Files.createDirectories(pkgDir);
        Path outFile = pkgDir.resolve(CLASS_NAME + ".java");
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(outFile))) {
            writeFile(w, plane, records);
        }
    }

    private static void writeFile(PrintWriter w, VServiceDiscovery.HostedVService plane,
                                  List<EventTopicDiscovery.TopicEvent> records) {
        String iface = plane.serviceName;
        String msgs = plane.outerClassName;
        w.println("// Copyright (c) 2024 Second Star Cavalier, LLC.");
        w.println("// GENERATED by stratum-codegen — do not edit.");
        w.println("// Source: spec.record types (EventBus topic events the record store holds).");
        w.println();
        w.println("package " + HOST_PKG + ";");
        w.println();
        w.println("import io.grpc.stub.StreamObserver;");
        w.println("import " + CALLER + ";");
        w.println("import " + PROTO_EXCEPTION + ";");
        w.println("import " + COLLECTION_RUNTIME + ";");
        w.println("import " + plane.messagesFqn() + ";");
        w.println("import " + plane.wrapperFqn(MODEL_BASE, SM_PREFIX) + ";");
        w.println();
        w.println("/**");
        w.println(" * C2S half of the record query plane. Every method delegates to the SAME");
        w.println(" * StratumRecordMaps instance the s2s half uses, so both surfaces share one");
        w.println(" * handle registry and one store view — the c2s vocabulary is a rename, not a");
        w.println(" * second implementation.");
        w.println(" *");
        w.println(" * Authorization is not done here: the generated " + iface + " wrapper runs the");
        w.println(" * Authorizer's entitlement path before any of these are reached, because the");
        w.println(" * service is c2s with auth_entitled_users.");
        w.println(" */");
        w.println("public final class " + CLASS_NAME + " implements " + iface + "." + iface + "Handler {");
        w.println();
        w.println("    private final StratumRecordMaps delegate;");
        w.println();
        w.println("    public " + CLASS_NAME + "(StratumRecordMaps delegate) {");
        w.println("        this.delegate = java.util.Objects.requireNonNull(delegate);");
        w.println("    }");

        for (EventTopicDiscovery.TopicEvent e : records) {
            String t = e.eventType;
            String fqn = fqn(e);
            boolean hasFilter = !e.queryFields.isEmpty();

            method(w, msgs + ".QueryHandle", "create" + t + "Query",
                    "Caller caller, " + msgs + ".Open" + t + "QueryRequest request",
                    "delegate." + lower("Create" + t + "Query") + "(caller, request)");
            method(w, msgs + ".RecordCount", "get" + t + "Count",
                    "Caller caller, " + msgs + ".QueryHandle request",
                    "delegate." + lower("Get" + t + "Count") + "(caller, request)");
            method(w, msgs + ".Sample" + t + "Response", "get" + t + "Sample",
                    "Caller caller, " + msgs + ".Sample" + t + "Request request",
                    "delegate." + lower("Get" + t + "Sample") + "(caller, request)");
            method(w, "CollectionRuntime.Page<" + fqn + ">", "list" + t,
                    "Caller caller, " + msgs + ".Pull" + t + "Request request, CollectionRuntime.PageParams page",
                    "delegate." + lower("List" + t) + "(caller, request, page)");
            method(w, msgs + ".QueryStats", "delete" + t + "Query",
                    "Caller caller, " + msgs + ".QueryHandle request",
                    "delegate." + lower("Delete" + t + "Query") + "(caller, request)");

            if (hasFilter) {
                method(w, msgs + ".QueryStats", "update" + t + "Query",
                        "Caller caller, " + msgs + ".Refine" + t + "Request request",
                        "delegate." + lower("Update" + t + "Query") + "(caller, request)");
                method(w, "CollectionRuntime.WatchSource<" + fqn + ", " + msgs + "." + t + "WatchChange>",
                        "watch" + t,
                        "Caller caller, " + msgs + ".QueryHandle request",
                        "delegate." + lower("Watch" + t) + "(caller, request)");
                // Streaming: no return value to forward.
                w.println();
                w.println("    @Override");
                w.println("    public void " + lower("Subscribe" + t + "Count")
                        + "(Caller caller, " + msgs + ".QueryHandle request, StreamObserver<" + msgs + ".RecordCount> responseObserver) throws ProtoException {");
                w.println("        delegate." + lower("Subscribe" + t + "Count")
                        + "(caller, request, responseObserver);");
                w.println("    }");
            }
        }

        w.println("}");
    }

    private static void method(PrintWriter w, String returnType, String name, String params, String call) {
        w.println();
        w.println("    @Override");
        w.println("    public " + returnType + " " + lower(name) + "(" + params + ") throws ProtoException {");
        w.println("        return " + call + ";");
        w.println("    }");
    }

    /** Lowercase the first character (RPC name -> Java method name). */
    private static String lower(String s) {
        return Character.toLowerCase(s.charAt(0)) + s.substring(1);
    }

    private static String fqn(EventTopicDiscovery.TopicEvent e) {
        return e.javaPackage + "." + e.outerClassName + "." + e.eventType;
    }
}
