    /**
     * "Is this filter a bare point read on the record key" as a Java expression
     * over {@code f} — the key criterion set and every other criterion unset.
     *
     * <p>Empty when the type's {@code <T>Filter} carries no EQ criterion on the
     * record key at all, which is every record that declares no
     * {@code s2s_read}: tacplus folds the key in only for those, so without it
     * the plane genuinely cannot express a by-key read and there is no shape to
     * exempt.
     */
    private static String pointRead(EventTopicDiscovery.TopicEvent e) {
        boolean hasKeyCriterion = false;
        for (EventTopicDiscovery.QueryField qf : e.queryFields) {
            if (qf.name.equals(e.recordKey) && !qf.range) {
                hasKeyCriterion = true;
                break;
            }
        }
        if (!hasKeyCriterion) {
            return "";
        }
        StringBuilder b = new StringBuilder("f.has" + pascal(e.recordKey) + "()");
        for (EventTopicDiscovery.QueryField qf : e.queryFields) {
            if (qf.name.equals(e.recordKey)) {
                continue;
            }
            String P = pascal(qf.name);
            if (qf.range) {
                b.append(" && !f.has").append(P).append("From() && !f.has").append(P).append("To()");
            } else {
                b.append(" && !f.has").append(P).append("()");
            }
        }
        return b.toString();
    }

    /** snake_case proto field -> PascalCase getter stem (spiffe_id -> SpiffeId). */
    private static String pascal(String snake) {
        StringBuilder b = new StringBuilder();
        boolean up = true;
        for (char c : snake.toCharArray()) {
            if (c == '_') { up = true; continue; }
            b.append(up ? Character.toUpperCase(c) : c);
            up = false;
        }
        return b.toString();
    }

    // ----- naming helpers (mirror EventStoreGenerator) -----

    private static String fqn(EventTopicDiscovery.TopicEvent e) {
        return e.javaPackage + "." + e.outerClassName + "." + e.eventType;
    }

    private static String field(EventTopicDiscovery.TopicEvent e) {
        return e.protoPackage + e.eventType;
    }

    /** Lowercase the first character (RPC name -> Java method name). */
    private static String lower(String s) {
        return Character.toLowerCase(s.charAt(0)) + s.substring(1);
    }
    /**
     * {@code @Override} for a record's s2s query methods — unless the record is
     * (spec.record).private, in which case tacplus emitted no S2S RecordMap RPCs
     * for it (record_map.go skips private types: a peer read has no caller
     * principal to pin the owner against) and there is nothing to override. The
     * methods are still emitted, un-annotated, because the C2S plane's impl is a
     * delegation shim onto them and the C2S plane DOES exist for a private type.
     */
    private static void overrideUnlessPrivate(PrintWriter w, EventTopicDiscovery.TopicEvent e) {
        if (!e.isPrivate) {
            w.println("    @Override");
        }
    }
