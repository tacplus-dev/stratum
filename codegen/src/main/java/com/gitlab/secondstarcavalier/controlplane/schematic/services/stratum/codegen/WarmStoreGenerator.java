package com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum.codegen;

import java.io.IOException;
import java.io.PrintWriter;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;

/**
 * Generates StratumWarmStores.java — the warm disk tier's dataset descriptors.
 *
 * One descriptor per record type declaring
 * {@code (spec.record).residency = {window: RESIDENCY_WARM}}. Each carries the
 * type's key, its store-epoch field, its mutability and its filterable fields —
 * i.e. exactly the same discovery {@link RecordMapImplGenerator} compiles the
 * in-memory {@code match<T>} from. The warm tier is a SECOND BACKEND for that one
 * field list, not a second source of truth, so a field that is filterable in
 * memory is filterable on disk by construction.
 *
 * The runtime that consumes these descriptors (the warm package) names no
 * vservice, which is the same split the hot store already has: generated typed
 * dispatch, hand-written generic mechanism.
 *
 * With no record type declaring RESIDENCY_WARM — which is every record today,
 * since absence means HOT — this emits an empty descriptor list. The wiring
 * around it is still generated and still compiled, so the tier is plumbed before
 * the first proto opts in rather than at the same time as it.
 */
public final class WarmStoreGenerator {

    private static final String HOST_PKG =
            "com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum";
    private static final String WARM_PKG = HOST_PKG + ".warm";
    private static final String CLASS_NAME = "StratumWarmStores";

    /** Proto scalar types whose Java getter already yields an integral value. */
    private static final Set<String> INTEGRAL = Set.of(
            "int32", "int64", "uint32", "uint64", "sint32", "sint64",
            "fixed32", "fixed64", "sfixed32", "sfixed64");

    private WarmStoreGenerator() {}

    public static void generate(Path outputDir, List<EventTopicDiscovery.TopicEvent> records)
            throws IOException {
        List<EventTopicDiscovery.TopicEvent> warm = new ArrayList<>();
        for (EventTopicDiscovery.TopicEvent e : records) {
            if (e.isWarm()) {
                warm.add(e);
            }
        }
        Path pkgDir = outputDir.resolve(HOST_PKG.replace('.', '/'));
        Files.createDirectories(pkgDir);
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(pkgDir.resolve(CLASS_NAME + ".java")))) {
            writeFile(w, warm);
        }
    }

    /** Package-private for tests: the emitted source, without touching the filesystem. */
    static String render(List<EventTopicDiscovery.TopicEvent> records) {
        List<EventTopicDiscovery.TopicEvent> warm = new ArrayList<>();
        for (EventTopicDiscovery.TopicEvent e : records) {
            if (e.isWarm()) {
                warm.add(e);
            }
        }
        java.io.StringWriter sw = new java.io.StringWriter();
        try (PrintWriter w = new PrintWriter(sw)) {
            writeFile(w, warm);
        }
        return sw.toString();
    }

    private static void writeFile(PrintWriter w, List<EventTopicDiscovery.TopicEvent> warm) {
        w.println("// Copyright (c) 2024 Second Star Cavalier, LLC.");
        w.println("// GENERATED by stratum-codegen — do not edit.");
        w.println("// Source: (spec.record).residency = {window: RESIDENCY_WARM} record types.");
        w.println();
        w.println("package " + HOST_PKG + ";");
        w.println();
        w.println("import java.util.ArrayList;");
        w.println("import java.util.List;");
        w.println();
        w.println("import " + WARM_PKG + ".WarmDataset;");
        w.println("import " + WARM_PKG + ".WarmField;");
        w.println();
        w.println("/**");
        w.println(" * Warm-tier dataset descriptors, one per RESIDENCY_WARM record type.");
        w.println(" *");
        w.println(" * The list is EMPTY when no record type declares the warm window — absence of");
        w.println(" * a residency clause is RESIDENCY_HOT, which is what every record does until");
        w.println(" * one opts in. An empty warm tier writes nothing and answers no disk leg.");
        w.println(" */");
        w.println("public final class " + CLASS_NAME + " {");
        w.println();
        w.println("    private " + CLASS_NAME + "() {}");
        w.println();
        w.println("    /**");
        w.println("     * @param defaultWindowSeconds the residency window for a record type that");
        w.println("     *                             declared the warm preset but no window_seconds");
        w.println("     *                             of its own");
        w.println("     */");
        w.println("    public static List<WarmDataset> datasets(long defaultWindowSeconds) {");
        w.println("        List<WarmDataset> out = new ArrayList<>();");
        for (EventTopicDiscovery.TopicEvent e : warm) {
            emitDataset(w, e);
        }
        w.println("        return out;");
        w.println("    }");
        w.println("}");
    }

    private static void emitDataset(PrintWriter w, EventTopicDiscovery.TopicEvent e) {
        String fqn = fqn(e);
        String epochField = requireStoreEpoch(e);
        String window = e.residencyWindowSeconds > 0
                ? Long.toString(e.residencyWindowSeconds) + "L"
                : "defaultWindowSeconds";
        w.println();
        w.println("        out.add(new WarmDataset(");
        w.println("                \"" + mapName(e) + "\",");
        w.println("                " + fqn + ".class,");
        w.println("                \"" + epochField + "\",");
        w.println("                " + e.isAppendOnly() + ",");
        w.println("                " + window + " * 1000L,");
        w.println("                List.of(");
        List<String> fields = new ArrayList<>();
        for (EventTopicDiscovery.QueryField qf : e.queryFields) {
            if (qf.name.equals(epochField)) {
                continue; // indexed as _epoch, never twice
            }
            fields.add("                        new WarmField(\"" + qf.name + "\", WarmField.Kind."
                    + kind(e, qf) + ", m -> " + valueExpr(fqn, e, qf) + ")");
        }
        w.println(String.join(",\n", fields));
        w.println("                ),");
        w.println("                m -> ((" + fqn + ") m).get" + pascal(e.recordKey) + "(),");
        w.println("                m -> ((" + fqn + ") m).get" + pascal(epochField) + "(),");
        w.println("                " + fqn + "::parseFrom,");
        w.println("                m -> " + e.javaPackage + ".Helpers.validate" + e.eventType
                + "((" + fqn + ") m)));");
    }

    /**
     * A warm record type with no (spec.store_epoch) field cannot be tiered: the
     * store epoch is what the two legs partition on, and there is no substitute for
     * it. The author's business timestamp is a different clock and using it would
     * put a row on the wrong side of the boundary the moment it is updated.
     */
    private static String requireStoreEpoch(EventTopicDiscovery.TopicEvent e) {
        if (e.storeEpochField.isEmpty()) {
            throw new IllegalStateException(mapName(e) + " declares residency ="
                    + " RESIDENCY_WARM but no field carries (spec.store_epoch), so the memory and"
                    + " disk legs have nothing to partition on. Annotate the record's store-epoch"
                    + " field in " + e.protoRelPath + ".");
        }
        return e.storeEpochField;
    }

    /** True when the proto scalar type's Java getter already yields an integral value. */
    static boolean isIntegral(String protoType) {
        return INTEGRAL.contains(protoType);
    }

    /**
     * True when the query field's type is an enum — i.e. not a scalar this knows.
     * An enum's numeric value is what both the index and the filter carry, and the
     * getter for it is {@code get<Field>Value()}, not {@code get<Field>()}.
     */
    static boolean isEnum(String protoType) {
        return !"string".equals(protoType) && !"bool".equals(protoType)
                && !INTEGRAL.contains(protoType)
                && (protoType.matches("[A-Z]\\w*") || protoType.contains("."));
    }

    private static String kind(EventTopicDiscovery.TopicEvent e, EventTopicDiscovery.QueryField qf) {
        if (qf.range) {
            return "RANGE_NUMERIC";
        }
        return "string".equals(qf.protoType) ? "EQ_STRING" : "EQ_NUMERIC";
    }

    /**
     * The Java expression reading one field off a record, as the value the disk
     * document indexes.
     *
     * A field type this does not know how to index is REFUSED here rather than
     * emitted as something that compiles and matches nothing. The in-memory
     * {@code match<T>} gets away with {@code !=} for every non-string type because
     * Java's operator covers numbers and enums alike; a Lucene point does not, so
     * the distinction has to be made rather than papered over.
     */
    private static String valueExpr(String fqn, EventTopicDiscovery.TopicEvent e,
                                    EventTopicDiscovery.QueryField qf) {
        String getter = "((" + fqn + ") m).get" + pascal(qf.name) + "()";
        if ("string".equals(qf.protoType)) {
            return getter;
        }
        if (INTEGRAL.contains(qf.protoType)) {
            return "(long) " + getter;
        }
        if ("bool".equals(qf.protoType)) {
            return getter + " ? 1L : 0L";
        }
        if (qf.protoType.matches("[A-Z]\\w*") || qf.protoType.contains(".")) {
            // An enum: indexed by its wire number, which is what the filter carries.
            return "(long) ((" + fqn + ") m).get" + pascal(qf.name) + "Value()";
        }
        throw new IllegalStateException(mapName(e) + "." + qf.name + " is a (spec.query_field) of"
                + " type " + qf.protoType + " on a RESIDENCY_WARM record, and the warm tier has no"
                + " index for it. Use a string, integral, bool or enum field, or drop the"
                + " query_field annotation in " + e.protoRelPath + ".");
    }

    // ----- naming helpers (mirror EventStoreGenerator) -----

    private static String fqn(EventTopicDiscovery.TopicEvent e) {
        return e.javaPackage + "." + e.outerClassName + "." + e.eventType;
    }

    private static String mapName(EventTopicDiscovery.TopicEvent e) {
        return e.protoPackage + "." + e.eventType;
    }

    /** snake_case proto field -> PascalCase getter stem (event_id -> EventId). */
    private static String pascal(String snake) {
        StringBuilder b = new StringBuilder();
        boolean up = true;
        for (char c : snake.toCharArray()) {
            if (c == '_') { up = true; continue; }
            b.append(up ? Character.toUpperCase(c) : c);
            up = false;
        }
        return b.toString();
    }
}
