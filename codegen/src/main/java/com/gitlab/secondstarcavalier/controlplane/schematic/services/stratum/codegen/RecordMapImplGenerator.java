package com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum.codegen;

import java.io.IOException;
import java.io.PrintWriter;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/**
 * Generates StratumRecordMaps.java — the implementation of the S2S half of the
 * generated record query plane. For every record type T (an EventBus topic event
 * the record store holds) it emits the query-handle RPC handlers the plane's
 * generated {@code <Service>Handler} interface declares:
 *
 *   create<T>Query  → register the caller's filter under a fresh query_id (handle)
 *   update<T>Query  → replace the handle's filter (narrow); filterable types only
 *   get<T>Count     → count records matching the handle's filter
 *   get<T>Sample    → seeded random sample of matching records
 *   list<T>         → typed PAGE of matching records
 *   watch<T>        → snapshot of matches + a live stream of matching records
 *   subscribe<T>Count → live count on each matching add/evict
 *   delete<T>Query  → drop the handle
 *
 * The handle→filter registry lives in this instance (queries). All per-type
 * knowledge is generated here; the generated StratumVServiceBase returns the
 * instance, so no hand-written code names the plane's service. Backed by
 * the generated StratumEventStores (typed hot IMaps) + RecordWatchHub (live
 * changes). Records return SOURCE RECORDS directly (the store holds them); a
 * federation caller may instead read keys and hydrate — both use the same filter.
 *
 * match<T>/list<T>/watch<T> are getter-based over the typed store (no Hazelcast
 * attribute-name coupling); list<T> pages via StratumHandler.pageSorted keyed by
 * the record key.
 */
public final class RecordMapImplGenerator {

    private static final String HOST_PKG =
            "com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum";
    private static final String MODEL_BASE = HOST_PKG + ".model";
    private static final String SM_PREFIX = "s2sm";
    private static final String CALLER = MODEL_BASE + ".chassis.servicemanager.Caller";
    private static final String PROTO_EXCEPTION = MODEL_BASE + ".types.sys.errors.ProtoException";
    private static final String COLLECTION_RUNTIME = MODEL_BASE + ".chassis.collection.CollectionRuntime";
    private static final String CLASS_NAME = "StratumRecordMaps";

    private RecordMapImplGenerator() {}

    /**
     * @param plane   the S2S half of the discovered record query plane; its
     *                service name and message outer class are what the emitted
     *                impl implements and speaks, both read off the declaration
     *                that produced the plane rather than fixed here
     * @param records the record types the plane serves
     */
    public static void generate(Path outputDir, VServiceDiscovery.HostedVService plane,
                                List<EventTopicDiscovery.TopicEvent> records)
            throws IOException {
        Path pkgDir = outputDir.resolve(HOST_PKG.replace('.', '/'));
        Files.createDirectories(pkgDir);
        Path outFile = pkgDir.resolve(CLASS_NAME + ".java");
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(outFile))) {
            writeFile(w, plane, records);
        }
    }

    private static void writeFile(PrintWriter w, VServiceDiscovery.HostedVService plane,
                                  List<EventTopicDiscovery.TopicEvent> records) {
        String iface = plane.serviceName;
        String msgs = plane.outerClassName;
        w.println("// Copyright (c) 2024 Second Star Cavalier, LLC.");
        w.println("// GENERATED by stratum-codegen — do not edit.");
        w.println("// Source: spec.record types (EventBus topic events the record store holds).");
        w.println();
        w.println("package " + HOST_PKG + ";");
        w.println();
        w.println("import java.util.ArrayList;");
        w.println("import java.util.UUID;");
        w.println("import java.util.concurrent.ConcurrentHashMap;");
        w.println("import java.util.function.Supplier;");
        w.println("import io.grpc.stub.StreamObserver;");
        w.println("import " + CALLER + ";");
        w.println("import " + PROTO_EXCEPTION + ";");
        w.println("import " + COLLECTION_RUNTIME + ";");
        w.println("import " + plane.messagesFqn() + ";");
        w.println("import " + plane.wrapperFqn(MODEL_BASE, SM_PREFIX) + ";");
        w.println();
        w.println("/**");
        w.println(" * Record-store query-plane implementation (" + iface + "). One RPC family per");
        w.println(" * record type; create<T>Query registers the caller's filter under a query_id");
        w.println(" * (handle) and every other op operates on that handle. Backed by the typed");
        w.println(" * StratumEventStores + RecordWatchHub.");
        w.println(" *");
        w.println(" * The stores are resolved per call via suppliers: StratumHandler rebuilds");
        w.println(" * them on every config update, so a captured reference would go stale. The");
        w.println(" * handle registry lives in this instance (obtained once via");
        w.println(" * get" + iface + "GrpcImpl and registered for the service lifetime).");
        w.println(" */");
        w.println("public final class " + CLASS_NAME + " implements " + iface + "." + iface + "Handler {");
        w.println();
        w.println("    private final Supplier<StratumEventStores> storesSupplier;");
        w.println("    // query_id -> the caller's typed filter (" + msgs + ".<T>Filter), or Boolean.TRUE");
        w.println("    // for filterless record types (match-all).");
        w.println("    private final ConcurrentHashMap<String, Object> queries = new ConcurrentHashMap<>();");
        w.println();
        w.println("    public " + CLASS_NAME + "(Supplier<StratumEventStores> storesSupplier) {");
        w.println("        this.storesSupplier = storesSupplier;");
        w.println("    }");
        w.println();
        w.println("    private StratumEventStores stores() { return storesSupplier.get(); }");
        w.println();
        w.println("    private Object requireQuery(String queryId) throws ProtoException {");
        w.println("        Object q = queries.get(queryId);");
        w.println("        if (q == null) throw new ProtoException(ProtoException.NOT_FOUND, \"unknown query_id: \" + queryId);");
        w.println("        return q;");
        w.println("    }");

        for (EventTopicDiscovery.TopicEvent e : records) {
            String t = e.eventType;      // e.g. AgentEvent
            String fqn = fqn(e);          // typed FQN
            String acc = field(e);        // stores accessor, e.g. agentsensorAgentEvent
            String keyGetter = "get" + pascal(e.recordKey);
            boolean hasFilter = !e.queryFields.isEmpty();
            String filterTy = msgs + "." + t + "Filter";
            String matchFn = lower("Match" + t);
            // Java expressions for "does record ev match the handle's predicate".
            String matchExpr = hasFilter ? (matchFn + "(f, ev)") : "true";
            String matchCast = hasFilter ? (matchFn + "(f, (" + fqn + ") m)") : "true";

            // match<T>: true when a record satisfies the typed filter. Getter-based,
            // no Hazelcast attribute coupling. Only for filterable record types.
            if (hasFilter) {
                w.println();
                w.println("    private static boolean " + matchFn + "(" + filterTy + " f, " + fqn + " ev) {");
                for (EventTopicDiscovery.QueryField qf : e.queryFields) {
                    String P = pascal(qf.name);
                    if (qf.range) {
                        w.println("        if (f.has" + P + "From() && ev.get" + P + "() < f.get" + P + "From()) return false;");
                        w.println("        if (f.has" + P + "To() && ev.get" + P + "() > f.get" + P + "To()) return false;");
                    } else if ("string".equals(qf.protoType)) {
                        w.println("        if (f.has" + P + "() && !ev.get" + P + "().equals(f.get" + P + "())) return false;");
                    } else {
                        w.println("        if (f.has" + P + "() && ev.get" + P + "() != f.get" + P + "()) return false;");
                    }
                }
                w.println("        return true;");
                w.println("    }");

                // <t>Filter(queryId): fetch + cast the handle's stored filter.
                w.println();
                w.println("    private " + filterTy + " " + lower(t) + "Filter(String queryId) throws ProtoException {");
                w.println("        return (" + filterTy + ") requireQuery(queryId);");
                w.println("    }");
            }

            // Emitted at the top of every store-scanning body: bind `f` to the
            // handle's filter (or validate existence for filterless types).
            String bindFilter = hasFilter
                    ? ("        " + filterTy + " f = " + lower(t) + "Filter(req.getQueryId());")
                    : "        requireQuery(req.getQueryId());";

            // create<T>Query — register the filter under a fresh handle.
            w.println();
            w.println("    @Override");
            w.println("    public " + msgs + ".QueryHandle " + lower("Create" + t + "Query")
                    + "(Caller caller, " + msgs + ".Open" + t + "QueryRequest req) throws ProtoException {");
            w.println("        String qid = UUID.randomUUID().toString();");
            w.println("        queries.put(qid, " + (hasFilter ? "req.getFilter()" : "Boolean.TRUE") + ");");
            w.println("        return " + msgs + ".QueryHandle.newBuilder().setQueryId(qid).build();");
            w.println("    }");

            // get<T>Count
            w.println();
            w.println("    @Override");
            w.println("    public " + msgs + ".RecordCount " + lower("Get" + t + "Count")
                    + "(Caller caller, " + msgs + ".QueryHandle req) throws ProtoException {");
            w.println(bindFilter);
            w.println("        long n = 0;");
            w.println("        try {");
            w.println("            for (" + fqn + " ev : stores()." + acc + "().values()) if (" + matchExpr + ") n++;");
            w.println("        } catch (Exception ex) {");
            w.println("            throw new ProtoException(ProtoException.INTERNAL, ex.getMessage());");
            w.println("        }");
            w.println("        return " + msgs + ".RecordCount.newBuilder().setCount(n).build();");
            w.println("    }");

            // get<T>Sample — seeded random sample of matching records.
            w.println();
            w.println("    @Override");
            w.println("    public " + msgs + ".Sample" + t + "Response " + lower("Get" + t + "Sample")
                    + "(Caller caller, " + msgs + ".Sample" + t + "Request req) throws ProtoException {");
            w.println(hasFilter
                    ? ("        " + filterTy + " f = " + lower(t) + "Filter(req.getQueryId());")
                    : "        requireQuery(req.getQueryId());");
            w.println("        java.util.List<" + fqn + "> matches = new ArrayList<>();");
            w.println("        try {");
            w.println("            for (" + fqn + " ev : stores()." + acc + "().values()) if (" + matchExpr + ") matches.add(ev);");
            w.println("        } catch (Exception ex) {");
            w.println("            throw new ProtoException(ProtoException.INTERNAL, ex.getMessage());");
            w.println("        }");
            w.println("        java.util.Collections.shuffle(matches, new java.util.Random(req.getSeed()));");
            w.println("        int lim = req.getN() > 0 ? Math.min(req.getN(), matches.size()) : matches.size();");
            w.println("        return " + msgs + ".Sample" + t + "Response.newBuilder()");
            w.println("                .addAllItems(matches.subList(0, lim)).build();");
            w.println("    }");

            // list<T> — typed PAGE of matching records, sorted by record key.
            w.println();
            w.println("    @Override");
            w.println("    public CollectionRuntime.Page<" + fqn + "> " + lower("List" + t)
                    + "(Caller caller, " + msgs + ".Pull" + t + "Request req, CollectionRuntime.PageParams page) throws ProtoException {");
            w.println(hasFilter
                    ? ("        " + filterTy + " f = " + lower(t) + "Filter(req.getQueryId());")
                    : "        requireQuery(req.getQueryId());");
            w.println("        java.util.List<" + fqn + "> matches = new ArrayList<>();");
            w.println("        try {");
            w.println("            for (" + fqn + " ev : stores()." + acc + "().values()) if (" + matchExpr + ") matches.add(ev);");
            w.println("        } catch (Exception ex) {");
            w.println("            throw new ProtoException(ProtoException.INTERNAL, ex.getMessage());");
            w.println("        }");
            w.println("        return StratumHandler.pageSorted(matches, page, ev -> java.util.List.of(ev." + keyGetter + "()));");
            w.println("    }");

            // delete<T>Query — drop the handle.
            w.println();
            w.println("    @Override");
            w.println("    public " + msgs + ".QueryStats " + lower("Delete" + t + "Query")
                    + "(Caller caller, " + msgs + ".QueryHandle req) throws ProtoException {");
            w.println("        queries.remove(req.getQueryId());");
            w.println("        return " + msgs + ".QueryStats.newBuilder().setQueryId(req.getQueryId()).setSize(0).build();");
            w.println("    }");

            // update<T>Query — replace the handle's filter outright. Not narrow-only: the
            // prior filter is never read, so a caller may widen back to match-all.
            // Filterable record types only.
            if (hasFilter) {
                w.println();
                w.println("    @Override");
                w.println("    public " + msgs + ".QueryStats " + lower("Update" + t + "Query")
                        + "(Caller caller, " + msgs + ".Refine" + t + "Request req) throws ProtoException {");
                w.println("        requireQuery(req.getQueryId());");
                w.println("        " + filterTy + " f = req.getFilter();");
                w.println("        queries.put(req.getQueryId(), f);");
                w.println("        long n = 0;");
                w.println("        try {");
                w.println("            for (" + fqn + " ev : stores()." + acc + "().values()) if (" + matchExpr + ") n++;");
                w.println("        } catch (Exception ex) {");
                w.println("            throw new ProtoException(ProtoException.INTERNAL, ex.getMessage());");
                w.println("        }");
                w.println("        return " + msgs + ".QueryStats.newBuilder().setQueryId(req.getQueryId()).setSize(n).build();");
                w.println("    }");
            }

            // watch<T> and subscribe<T>Count — filterable record types only.
            // These piggyback on the query handle; a filterless record has no
            // query to watch, so the generated interface omits them.
            if (hasFilter) {
                // watch<T> — snapshot of matching records + live change stream.
                w.println();
                w.println("    @Override");
                w.println("    public " + COLLECTION_RUNTIME + ".WatchSource<" + fqn + ", " + msgs + "." + t + "WatchChange> " + lower("Watch" + t)
                        + "(Caller caller, " + msgs + ".QueryHandle req) throws ProtoException {");
                w.println(bindFilter);
                w.println("        java.util.List<" + fqn + "> matches = new ArrayList<>();");
                w.println("        try {");
                w.println("            for (" + fqn + " ev : stores()." + acc + "().values()) if (" + matchExpr + ") matches.add(ev);");
                w.println("        } catch (Exception ex) {");
                w.println("            throw new ProtoException(ProtoException.INTERNAL, ex.getMessage());");
                w.println("        }");
                w.println("        return new " + COLLECTION_RUNTIME + ".WatchSource<>(");
                w.println("                \"recordmap." + lower(t) + "\", matches.iterator(), 0L,");
                w.println("                () -> java.util.Collections.<" + msgs + "." + t + "WatchChange>emptyIterator());");
                w.println("    }");

                // subscribe<T>Count — live count on each matching add/evict.
                w.println();
                w.println("    @Override");
                w.println("    public void " + lower("Subscribe" + t + "Count")
                        + "(Caller caller, " + msgs + ".QueryHandle req, StreamObserver<" + msgs + ".RecordCount> responseObserver) throws ProtoException {");
                w.println(bindFilter);
                w.println("        long n = 0;");
                w.println("        try {");
                w.println("            for (" + fqn + " ev : stores()." + acc + "().values()) if (" + matchExpr + ") n++;");
                w.println("        } catch (Exception ex) {");
                w.println("            throw new ProtoException(ProtoException.INTERNAL, ex.getMessage());");
                w.println("        }");
                w.println("        responseObserver.onNext(" + msgs + ".RecordCount.newBuilder().setCount(n).build());");
                w.println("        responseObserver.onCompleted();");
                w.println("    }");
            }

        }

        w.println("}");
    }

    /** snake_case proto field -> PascalCase getter stem (spiffe_id -> SpiffeId). */
    private static String pascal(String snake) {
        StringBuilder b = new StringBuilder();
        boolean up = true;
        for (char c : snake.toCharArray()) {
            if (c == '_') { up = true; continue; }
            b.append(up ? Character.toUpperCase(c) : c);
            up = false;
        }
        return b.toString();
    }

    // ----- naming helpers (mirror EventStoreGenerator) -----

    private static String fqn(EventTopicDiscovery.TopicEvent e) {
        return e.javaPackage + "." + e.outerClassName + "." + e.eventType;
    }

    private static String field(EventTopicDiscovery.TopicEvent e) {
        return e.protoPackage + e.eventType;
    }

    /** Lowercase the first character (RPC name -> Java method name). */
    private static String lower(String s) {
        return Character.toLowerCase(s.charAt(0)) + s.substring(1);
    }
}
