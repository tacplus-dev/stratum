package com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum.codegen;

import java.io.IOException;
import java.io.PrintWriter;
import java.io.StringWriter;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;

/**
 * Generates StratumHotStores.java — the hot tier's redo-log descriptors.
 *
 * One descriptor per record type that can be replayed: its map name, its declared
 * durability floor, and the three functions recovery needs (key, store epoch,
 * JSON both ways). {@code StratumEventStores} writes the rows; these descriptors
 * are what lets the hot package open a log per type and merge a replayed record
 * back without naming a vservice — the same generated-descriptors /
 * hand-written-mechanism split the warm tier has.
 *
 * <h2>Why a record with no (spec.store_epoch) gets no redo log</h2>
 * Each node's log is partial, so recovery is a union across nodes resolved by the
 * row's store epoch. A record with no store-epoch field has nothing to resolve by,
 * and the substitutes are all wrong: the author's business timestamp is a
 * different clock, and file position is only causal within ONE node's log. Such a
 * record keeps its in-memory replication and its quorum gate and is listed here as
 * NOT replayable, rather than given a redo log that cannot be safely merged. It is
 * the same refusal {@link WarmStoreGenerator} makes for the warm tier, for the
 * same reason.
 */
public final class HotStoreGenerator {

    private static final String HOST_PKG =
            "com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum";
    private static final String HOT_PKG = HOST_PKG + ".hot";
    private static final String CLASS_NAME = "StratumHotStores";

    private HotStoreGenerator() {}

    public static void generate(Path outputDir, List<EventTopicDiscovery.TopicEvent> records)
            throws IOException {
        Path pkgDir = outputDir.resolve(HOST_PKG.replace('.', '/'));
        Files.createDirectories(pkgDir);
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(pkgDir.resolve(CLASS_NAME + ".java")))) {
            writeFile(w, replayable(records));
        }
    }

    /** Package-private for tests: the emitted source, without touching the filesystem. */
    static String render(List<EventTopicDiscovery.TopicEvent> records) {
        StringWriter sw = new StringWriter();
        try (PrintWriter w = new PrintWriter(sw)) {
            writeFile(w, replayable(records));
        }
        return sw.toString();
    }

    /** The record types whose rows can be resolved across nodes at restore. */
    private static List<EventTopicDiscovery.TopicEvent> replayable(
            List<EventTopicDiscovery.TopicEvent> records) {
        List<EventTopicDiscovery.TopicEvent> out = new ArrayList<>();
        for (EventTopicDiscovery.TopicEvent e : records) {
            if (e.isRecord && !e.storeEpochField.isEmpty()) {
                out.add(e);
            }
        }
        return out;
    }

    private static void writeFile(PrintWriter w, List<EventTopicDiscovery.TopicEvent> records) {
        w.println("// Copyright (c) 2024 Second Star Cavalier, LLC.");
        w.println("// GENERATED by stratum-codegen — do not edit.");
        w.println("// Source: record types carrying (spec.store_epoch).");
        w.println();
        w.println("package " + HOST_PKG + ";");
        w.println();
        w.println("import java.util.ArrayList;");
        w.println("import java.util.List;");
        w.println();
        w.println("import " + HOT_PKG + ".HotDataset;");
        w.println();
        w.println("/**");
        w.println(" * Hot-tier redo-log descriptors, one per replayable record type.");
        w.println(" *");
        w.println(" * The list is EMPTY when no record carries (spec.store_epoch) — the hot tier");
        w.println(" * then keeps its in-memory replication and its quorum gate and writes no redo");
        w.println(" * log, because a partial per-node log with no epoch cannot be unioned back.");
        w.println(" */");
        w.println("public final class " + CLASS_NAME + " {");
        w.println();
        w.println("    private " + CLASS_NAME + "() {}");
        w.println();
        w.println("    public static List<HotDataset> datasets() {");
        w.println("        List<HotDataset> out = new ArrayList<>();");
        for (EventTopicDiscovery.TopicEvent e : records) {
            emitDataset(w, e);
        }
        w.println("        return out;");
        w.println("    }");
        w.println("}");
    }

    private static void emitDataset(PrintWriter w, EventTopicDiscovery.TopicEvent e) {
        String fqn = fqn(e);
        String helpers = e.javaPackage + ".Helpers";
        String lower = Character.toLowerCase(e.eventType.charAt(0)) + e.eventType.substring(1);
        w.println();
        w.println("        out.add(new HotDataset(");
        w.println("                \"" + mapName(e) + "\",");
        w.println("                " + e.minDurableCopies + ",");
        w.println("                m -> ((" + fqn + ") m).get" + pascal(e.recordKey) + "(),");
        w.println("                m -> ((" + fqn + ") m).get" + pascal(e.storeEpochField) + "(),");
        w.println("                \"" + e.storeEpochField + "\",");
        w.println("                m -> {");
        w.println("                    try {");
        w.println("                        return " + helpers + "." + lower + "ToJson((" + fqn + ") m);");
        w.println("                    } catch (Exception ex) {");
        w.println("                        throw new IllegalArgumentException(\"" + mapName(e)
                + " cannot be encoded for the redo log\", ex);");
        w.println("                    }");
        w.println("                },");
        w.println("                json -> {");
        w.println("                    try {");
        w.println("                        return " + helpers + "." + lower + "FromJson(json);");
        w.println("                    } catch (Exception ex) {");
        w.println("                        throw new IllegalStateException(\"" + mapName(e)
                + " redo record could not be decoded\", ex);");
        w.println("                    }");
        w.println("                }));");
    }

    // ----- naming helpers (mirror EventStoreGenerator) -----

    private static String fqn(EventTopicDiscovery.TopicEvent e) {
        return e.javaPackage + "." + e.outerClassName + "." + e.eventType;
    }

    private static String mapName(EventTopicDiscovery.TopicEvent e) {
        return e.protoPackage + "." + e.eventType;
    }

    /** snake_case proto field -> PascalCase getter stem (event_id -> EventId). */
    private static String pascal(String snake) {
        StringBuilder b = new StringBuilder();
        boolean up = true;
        for (char c : snake.toCharArray()) {
            if (c == '_') { up = true; continue; }
            b.append(up ? Character.toUpperCase(c) : c);
            up = false;
        }
        return b.toString();
    }
}
