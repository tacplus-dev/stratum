package com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum.codegen;

import java.io.IOException;
import java.io.PrintWriter;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/**
 * Generates StratumEventStores.java — the typed, per-vservice hot store.
 *
 * For every EventBus topic event type (discovered by {@link EventTopicDiscovery})
 * it emits a typed {@code IMap<String, EventType>} plus generic operations
 * ({@code store}, {@code totalCount}, {@code runRetention}). Stratum's
 * hand-written code calls only those generic operations and never names a
 * vservice — so adding a vservice (or .off-ing its proto) regenerates this
 * class with no hand-edit, satisfying: a service contains no hand-written
 * knowledge of the vservices it hosts.
 *
 * This is the Stratum analogue of TimeDB's generated timeseries dispatch and
 * GraphDB's generated graph projections — the "insert the event" biz-logic,
 * generated from the vservice definition.
 */
public final class EventStoreGenerator {

    private static final String HOST_PKG =
            "com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum";
    private static final String CLASS_NAME = "StratumEventStores";

    private EventStoreGenerator() {}

    public static void generate(Path outputDir, List<EventTopicDiscovery.TopicEvent> events)
            throws IOException {
        Path pkgDir = outputDir.resolve(HOST_PKG.replace('.', '/'));
        Files.createDirectories(pkgDir);
        Path outFile = pkgDir.resolve(CLASS_NAME + ".java");
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(outFile))) {
            writeFile(w, events);
        }
    }

    private static void writeFile(PrintWriter w, List<EventTopicDiscovery.TopicEvent> events) {
        w.println("// Copyright (c) 2024 Second Star Cavalier, LLC.");
        w.println("// GENERATED by stratum-codegen — do not edit.");
        w.println("// Source: EventBus topic event types across the vservice protos.");
        w.println();
        w.println("package " + HOST_PKG + ";");
        w.println();
        w.println("import com.google.protobuf.Message;");
        w.println("import com.hazelcast.core.HazelcastInstance;");
        w.println("import com.hazelcast.map.IMap;");
        w.println("import com.hazelcast.query.Predicates;");
        w.println("import org.slf4j.Logger;");
        w.println("import org.slf4j.LoggerFactory;");
        w.println();
        w.println("/**");
        w.println(" * Typed per-vservice hot store. One IMap<event_id, EventType> per");
        w.println(" * EventBus topic; generic store/count/retention over all of them.");
        w.println(" */");
        w.println("public final class " + CLASS_NAME + " {");
        w.println();
        w.println("    private static final Logger LOG = LoggerFactory.getLogger("
                + CLASS_NAME + ".class);");
        w.println();

        // Fields: one typed IMap per event type.
        for (EventTopicDiscovery.TopicEvent e : events) {
            w.println("    private IMap<String, " + fqn(e) + "> " + field(e) + ";");
        }
        w.println();

        // init
        w.println("    /** Binds each typed map on the shared Hazelcast instance. */");
        w.println("    public void init(HazelcastInstance hz) {");
        for (EventTopicDiscovery.TopicEvent e : events) {
            w.println("        " + field(e) + " = hz.getMap(\"" + mapName(e) + "\");");
        }
        w.println("    }");
        w.println();

        // store
        w.println("    /**");
        w.println("     * Stores any subscribed event into its typed map, keyed by event_id.");
        w.println("     *");
        w.println("     * Each event is validated with the SAME generated validator the read");
        w.println("     * path enforces before it is put. Without this the store accepts records");
        w.println("     * it can never serve: the read side validates every item in a page and");
        w.println("     * fails the whole response, so ONE malformed event makes every query");
        w.println("     * return Internal \"field X must be defined\" for as long as it is held.");
        w.println("     * Observed on stratum: a single AgentEvent with event_type unset, in a");
        w.println("     * map of 71, took the entire RecordMap query RPC down, and the failure");
        w.println("     * read as \"the store is empty\".");
        w.println("     *");
        w.println("     * A rejected event is dropped and logged, not rethrown: this runs on the");
        w.println("     * EventBus subscription thread, and throwing would make the subscriber");
        w.println("     * retry the same poison record forever.");
        w.println("     *");
        w.println("     * @return true if the type was recognised — including when the event was");
        w.println("     *         rejected as invalid. False means no typed store handles it.");
        w.println("     */");
        w.println("    public boolean store(Message msg) {");
        for (EventTopicDiscovery.TopicEvent e : events) {
            String keyGetter = "get" + pascal(e.recordKey);
            w.println("        if (msg instanceof " + fqn(e) + ") {");
            w.println("            " + fqn(e) + " e = (" + fqn(e) + ") msg;");
            w.println("            try {");
            w.println("                " + validator(e) + "(e);");
            w.println("            } catch (Exception ex) {");
            w.println("                LOG.warn(\"rejected unstorable " + mapName(e)
                    + " " + e.recordKey + "={}: {}\", e." + keyGetter + "(), ex.getMessage());");
            w.println("                return true;");
            w.println("            }");
            w.println("            " + field(e) + ".put(e." + keyGetter + "(), e);");
            w.println("            return true;");
            w.println("        }");
        }
        w.println("        return false;");
        w.println("    }");
        w.println();

        // totalCount
        w.println("    /** Total events across all typed stores. */");
        w.println("    public long totalCount() {");
        w.println("        long n = 0;");
        for (EventTopicDiscovery.TopicEvent e : events) {
            w.println("        n += " + field(e) + ".size();");
        }
        w.println("        return n;");
        w.println("    }");
        w.println();

        // runRetention
        w.println("    /** Removes events older than cutoffMs from every typed store. */");
        w.println("    public void runRetention(long cutoffMs) {");
        for (EventTopicDiscovery.TopicEvent e : events) {
            w.println("        " + field(e) + ".removeAll(Predicates.lessThan(\"timestampMs\", cutoffMs));");
        }
        w.println("    }");
        w.println();

        // typed accessors (read path)
        for (EventTopicDiscovery.TopicEvent e : events) {
            w.println("    public IMap<String, " + fqn(e) + "> " + field(e) + "() { return " + field(e) + "; }");
        }

        w.println("}");
    }

    // ----- naming helpers -----

    /** Java FQN of the event type, derived from the proto's java_package + java_outer_classname. */
    private static String fqn(EventTopicDiscovery.TopicEvent e) {
        return e.javaPackage + "." + e.outerClassName + "." + e.eventType;
    }

    /** Hazelcast map name, e.g. "agentsensor.AgentEvent". */
    static String mapName(EventTopicDiscovery.TopicEvent e) {
        return e.protoPackage + "." + e.eventType;
    }

    /** Field/accessor identifier, e.g. "agentsensorAgentEvent". */
    private static String field(EventTopicDiscovery.TopicEvent e) {
        return e.protoPackage + e.eventType;
    }

    /**
     * Generated validator for an event type, e.g.
     * "…model.types.services.tasks.Helpers.validateTaskActivity".
     * Helpers sits beside the outer proto class, in the same java_package.
     */
    private static String validator(EventTopicDiscovery.TopicEvent e) {
        return e.javaPackage + ".Helpers.validate" + e.eventType;
    }

    /** snake_case proto field -> PascalCase getter stem (event_id -> EventId). */
    private static String pascal(String snake) {
        StringBuilder b = new StringBuilder();
        boolean up = true;
        for (char c : snake.toCharArray()) {
            if (c == '_') { up = true; continue; }
            b.append(up ? Character.toUpperCase(c) : c);
            up = false;
        }
        return b.toString();
    }
}
