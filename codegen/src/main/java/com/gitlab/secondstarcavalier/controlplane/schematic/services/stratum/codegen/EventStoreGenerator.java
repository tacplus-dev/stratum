package com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum.codegen;

import java.io.IOException;
import java.io.PrintWriter;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/**
 * Generates StratumEventStores.java — the typed, per-vservice hot store.
 *
 * For every EventBus topic event type (discovered by {@link EventTopicDiscovery})
 * it emits a typed {@code IMap<String, EventType>} plus generic operations
 * ({@code store}, {@code totalCount}, {@code runRetention}). Stratum's
 * hand-written code calls only those generic operations and never names a
 * vservice — so adding a vservice (or .off-ing its proto) regenerates this
 * class with no hand-edit, satisfying: a service contains no hand-written
 * knowledge of the vservices it hosts.
 *
 * This is the Stratum analogue of TimeDB's generated timeseries dispatch and
 * GraphDB's generated graph projections — the "insert the event" biz-logic,
 * generated from the vservice definition.
 */
public final class EventStoreGenerator {

    private static final String HOST_PKG =
            "com.gitlab.secondstarcavalier.controlplane.schematic.services.stratum";
    private static final String CLASS_NAME = "StratumEventStores";

    private EventStoreGenerator() {}

    public static void generate(Path outputDir, List<EventTopicDiscovery.TopicEvent> events)
            throws IOException {
        Path pkgDir = outputDir.resolve(HOST_PKG.replace('.', '/'));
        Files.createDirectories(pkgDir);
        Path outFile = pkgDir.resolve(CLASS_NAME + ".java");
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(outFile))) {
            writeFile(w, events);
        }
    }

    private static void writeFile(PrintWriter w, List<EventTopicDiscovery.TopicEvent> events) {
        w.println("// Copyright (c) 2024 Second Star Cavalier, LLC.");
        w.println("// GENERATED by stratum-codegen — do not edit.");
        w.println("// Source: EventBus topic event types across the vservice protos.");
        w.println();
        w.println("package " + HOST_PKG + ";");
        w.println();
        w.println("import com.google.protobuf.Message;");
        w.println("import com.hazelcast.core.HazelcastInstance;");
        w.println("import com.hazelcast.map.IMap;");
        w.println("import com.hazelcast.query.Predicates;");
        w.println("import " + HOST_PKG + ".hot.HotWrites;");
        w.println("import org.slf4j.Logger;");
        w.println("import org.slf4j.LoggerFactory;");
        w.println();
        w.println("/**");
        w.println(" * Typed per-vservice hot store. One IMap<event_id, EventType> per");
        w.println(" * EventBus topic; generic store/count/retention over all of them.");
        w.println(" */");
        w.println("public final class " + CLASS_NAME + " {");
        w.println();
        w.println("    private static final Logger LOG = LoggerFactory.getLogger("
                + CLASS_NAME + ".class);");
        w.println();

        // Fields: one typed IMap per event type.
        for (EventTopicDiscovery.TopicEvent e : events) {
            w.println("    private IMap<String, " + fqn(e) + "> " + field(e) + ";");
        }
        w.println("    private HotWrites hot;");
        w.println();

        // Per-record durability floor: the strictest (spec.min_durable_copies) the
        // record declares, defaulted to 2. Emitted as a constant so the map's
        // backupCount and the write gate read ONE number, not two that can drift.
        for (EventTopicDiscovery.TopicEvent e : events) {
            w.println("    /** Distinct nodes a " + mapName(e)
                    + " write must reach before it is acked. */");
            w.println("    public static final int " + floorConst(e) + " = " + e.minDurableCopies + ";");
        }
        w.println();

        // init
        w.println("    /**");
        w.println("     * Binds each typed map on the shared Hazelcast instance.");
        w.println("     *");
        w.println("     * @param hot the hot write path — the quorum gate plus the backup-aware");
        w.println("     *            redo append. Every write goes through it; a bare put would");
        w.println("     *            give the second in-memory copy and no durability leg at all.");
        w.println("     */");
        w.println("    public void init(HazelcastInstance hz, HotWrites hot) {");
        w.println("        this.hot = hot;");
        for (EventTopicDiscovery.TopicEvent e : events) {
            w.println("        " + field(e) + " = hz.getMap(\"" + mapName(e) + "\");");
        }
        w.println("    }");
        w.println();

        // store
        w.println("    /**");
        w.println("     * Stores any subscribed event into its typed map, keyed by event_id.");
        w.println("     *");
        w.println("     * Each event is validated with the SAME generated validator the read");
        w.println("     * path enforces before it is put. Without this the store accepts records");
        w.println("     * it can never serve: the read side validates every item in a page and");
        w.println("     * fails the whole response, so ONE malformed event makes every query");
        w.println("     * return Internal \"field X must be defined\" for as long as it is held.");
        w.println("     * Observed on stratum: a single AgentEvent with event_type unset, in a");
        w.println("     * map of 71, took the entire RecordMap query RPC down, and the failure");
        w.println("     * read as \"the store is empty\".");
        w.println("     *");
        w.println("     * A rejected event is dropped and logged, not rethrown: this runs on the");
        w.println("     * EventBus subscription thread, and throwing would make the subscriber");
        w.println("     * retry the same poison record forever.");
        w.println("     *");
        w.println("     * The write goes through HotWrites: the durability floor is checked");
        w.println("     * BEFORE any local effect, and the value and its redo append ride the same");
        w.println("     * replication, so the two logs that recorded it are the two instances that");
        w.println("     * hold it. A below-quorum write throws rather than storing locally.");
        w.println("     *");
        w.println("     * @return true if the type was recognised — including when the event was");
        w.println("     *         rejected as invalid. False means no typed store handles it.");
        w.println("     */");
        w.println("    public boolean store(Message msg) {");
        for (EventTopicDiscovery.TopicEvent e : events) {
            String keyGetter = "get" + pascal(e.recordKey);
            w.println("        if (msg instanceof " + fqn(e) + ") {");
            w.println("            " + fqn(e) + " e = (" + fqn(e) + ") msg;");
            w.println("            try {");
            w.println("                " + validator(e) + "(e);");
            w.println("            } catch (Exception ex) {");
            w.println("                LOG.warn(\"rejected unstorable " + mapName(e)
                    + " " + e.recordKey + "={}: {}\", e." + keyGetter + "(), ex.getMessage());");
            w.println("                return true;");
            w.println("            }");
            w.println("            hot.write(" + field(e) + ", \"" + mapName(e) + "\", e."
                    + keyGetter + "(), e, " + floorConst(e) + ",");
            w.println("                    () -> " + helpers(e) + "." + lowerType(e) + "ToJson(e), "
                    + epochExpr(e) + ");");
            w.println("            return true;");
            w.println("        }");
        }
        w.println("        return false;");
        w.println("    }");
        w.println();

        // totalCount
        w.println("    /** Total events across all typed stores. */");
        w.println("    public long totalCount() {");
        w.println("        long n = 0;");
        for (EventTopicDiscovery.TopicEvent e : events) {
            w.println("        n += " + field(e) + ".size();");
        }
        w.println("        return n;");
        w.println("    }");
        w.println();

        // runRetention
        w.println("    /** Removes events older than cutoffMs from every typed store. */");
        w.println("    public void runRetention(long cutoffMs) {");
        for (EventTopicDiscovery.TopicEvent e : events) {
            w.println("        " + field(e) + ".removeAll(Predicates.lessThan(\""
                    + retentionAttribute(e) + "\", cutoffMs));");
        }
        w.println("    }");
        w.println();

        // mapNames — the Hazelcast names of every typed store, for the Config builder.
        //
        // Emitted rather than hand-listed because StratumMapConfig has to give EVERY
        // record map the same durability settings, and a hand-written list is a
        // second place the record set is recorded: it goes stale the moment a proto
        // is added or .off-ed, and a map missing from it silently falls back to
        // Hazelcast's defaults — one backup and NO split-brain protection — under a
        // config that claims to state both.
        w.println("    /** Every typed store's Hazelcast map name, in declaration order. */");
        StringBuilder names = new StringBuilder();
        for (EventTopicDiscovery.TopicEvent e : events) {
            if (names.length() > 0) {
                names.append(", ");
            }
            names.append('"').append(mapName(e)).append('"');
        }
        w.println("    public static java.util.List<String> mapNames() {");
        w.println("        return java.util.List.of(" + names + ");");
        w.println("    }");
        w.println();

        // minDurableCopies(mapName) — the floorConst() constants keyed by map name, for
        // callers (StratumMapConfig) that only have the name, not the record type, in hand.
        w.println("    /** The declared durability floor for a map name, or 0 if unknown. */");
        w.println("    public static int minDurableCopies(String mapName) {");
        w.println("        switch (mapName) {");
        for (EventTopicDiscovery.TopicEvent e : events) {
            w.println("            case \"" + mapName(e) + "\": return " + floorConst(e) + ";");
        }
        w.println("            default: return 0;");
        w.println("        }");
        w.println("    }");
        w.println();

        // typed accessors (read path)
        for (EventTopicDiscovery.TopicEvent e : events) {
            w.println("    public IMap<String, " + fqn(e) + "> " + field(e) + "() { return " + field(e) + "; }");
        }

        w.println("}");
    }

    // ----- naming helpers -----

    /** The emitted per-record durability-floor constant, e.g. MIN_DURABLE_COPIES_AGENTSENSOR_AGENT_EVENT. */
    private static String floorConst(EventTopicDiscovery.TopicEvent e) {
        return "MIN_DURABLE_COPIES_" + mapName(e).replace('.', '_')
                .replaceAll("([a-z0-9])([A-Z])", "$1_$2").toUpperCase(java.util.Locale.ROOT);
    }

    /** The generated Helpers class beside the outer proto class. */
    private static String helpers(EventTopicDiscovery.TopicEvent e) {
        return e.javaPackage + ".Helpers";
    }

    /** lowerCamel type name, the stem of the generated ToJson/FromJson helpers. */
    private static String lowerType(EventTopicDiscovery.TopicEvent e) {
        return Character.toLowerCase(e.eventType.charAt(0)) + e.eventType.substring(1);
    }

    /**
     * The store epoch stamped into the redo record.
     *
     * The record's own (spec.store_epoch) field when it declares one — the write
     * time the row's two legs already partition on. A record that declares none is
     * not replayable at all (see HotStoreGenerator), so it has no epoch to read and
     * its redo append never happens; 0 is emitted to keep the call shape uniform
     * rather than to stand in for a clock.
     */
    private static String epochExpr(EventTopicDiscovery.TopicEvent e) {
        if (e.storeEpochField.isEmpty()) {
            return "0L";
        }
        return "e.get" + pascal(e.storeEpochField) + "()";
    }

    /** Java FQN of the event type, derived from the proto's java_package + java_outer_classname. */
    private static String fqn(EventTopicDiscovery.TopicEvent e) {
        return e.javaPackage + "." + e.outerClassName + "." + e.eventType;
    }

    /** Hazelcast map name, e.g. "agentsensor.AgentEvent". */
    static String mapName(EventTopicDiscovery.TopicEvent e) {
        return e.protoPackage + "." + e.eventType;
    }

    /** Field/accessor identifier, e.g. "agentsensorAgentEvent". */
    private static String field(EventTopicDiscovery.TopicEvent e) {
        return e.protoPackage + e.eventType;
    }

    /**
     * Generated validator for an event type, e.g.
     * "…model.types.services.tasks.Helpers.validateTaskActivity".
     * Helpers sits beside the outer proto class, in the same java_package.
     */
    private static String validator(EventTopicDiscovery.TopicEvent e) {
        return e.javaPackage + ".Helpers.validate" + e.eventType;
    }

    /**
     * The Hazelcast attribute the retention sweep filters on, for one event type.
     *
     * Hazelcast resolves a predicate attribute by reflecting for a JavaBean
     * getter, so the name must be the camelCase property (occurredAtMs ->
     * getOccurredAtMs()), not the proto field name. Which field carries the
     * event's age is declared per record by
     * (spec.record).retention.timestamp_field — it is
     * "timestamp_ms" on AgentEvent but "occurred_at_ms" on TaskActivity, so a
     * single hard-coded name is wrong for some record type by construction.
     * Emitting the wrong one is silent at build time and fails only at run time,
     * inside the scheduled sweep, where a QueryException aborts the whole
     * retention pass — including the maps whose name WAS right — and the store
     * grows without bound.
     *
     * A stored record with no retention policy has no field to measure age from
     * and could never be swept, so it is rejected here rather than generated
     * into a sweep that cannot work.
     */
    private static String retentionAttribute(EventTopicDiscovery.TopicEvent e) {
        if (e.retentionTimestampField.isEmpty()) {
            throw new IllegalStateException(mapName(e) + " is stored by stratum but declares no"
                    + " (spec.record).retention.timestamp_field, so the retention sweep has no"
                    + " field to measure event age from. Declare a retention policy on the"
                    + " record's (spec.record) annotation in " + e.protoRelPath + ".");
        }
        return camel(e.retentionTimestampField);
    }

    /** snake_case proto field -> lowerCamelCase property (occurred_at_ms -> occurredAtMs). */
    private static String camel(String snake) {
        String p = pascal(snake);
        return Character.toLowerCase(p.charAt(0)) + p.substring(1);
    }

    /** snake_case proto field -> PascalCase getter stem (event_id -> EventId). */
    private static String pascal(String snake) {
        StringBuilder b = new StringBuilder();
        boolean up = true;
        for (char c : snake.toCharArray()) {
            if (c == '_') { up = true; continue; }
            b.append(up ? Character.toUpperCase(c) : c);
            up = false;
        }
        return b.toString();
    }
}
