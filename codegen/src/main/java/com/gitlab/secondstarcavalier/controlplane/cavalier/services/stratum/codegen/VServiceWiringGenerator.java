package com.gitlab.secondstarcavalier.controlplane.services.stratum.codegen;

import java.io.IOException;
import java.io.PrintWriter;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/**
 * Generates StratumVServiceBase.java — an abstract base class that bridges the
 * tacplus-generated Handler interface to stratum's vservice implementations.
 *
 * For each discovered hosted vservice (e.g. StratumQuery), the generated class:
 *   1. Implements get{ServiceName}GrpcImpl() by delegating to provide{ServiceName}Handler()
 *   2. Implements handle{ServiceName}Config(Stratum.Config) by delegating to handleConfig()
 *   3. Declares abstract methods provide{ServiceName}Handler() and handleConfig()
 *
 * StratumHandler extends this generated base class and only needs to implement
 * the abstract methods for each hosted vservice.
 *
 * When a new vservice is added with {tag: "stratum"}, the codegen automatically
 * adds the corresponding abstract methods — stratum never needs manual wiring.
 */
public class VServiceWiringGenerator {

    private static final String HOST_PKG_BASE = "com.gitlab.secondstarcavalier.controlplane.services.stratum";
    private static final String TACPLUS_BASE = HOST_PKG_BASE + ".tacplus";
    private static final String SM_PREFIX = "s2sm";

    /**
     * Generates StratumVServiceBase.java into the given output directory.
     *
     * @param outputDir  root source output directory
     * @param services   discovered vservices with {tag: "stratum"}
     */
    public static void generate(Path outputDir, List<VServiceDiscovery.HostedVService> services)
            throws IOException {
        String pkg = HOST_PKG_BASE;
        Path pkgDir = outputDir.resolve(pkg.replace('.', '/'));
        Files.createDirectories(pkgDir);

        Path outFile = pkgDir.resolve("StratumVServiceBase.java");
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(outFile))) {
            writeFile(w, pkg, services);
        }
    }

    private static void writeFile(PrintWriter w, String pkg,
                                   List<VServiceDiscovery.HostedVService> services) {
        w.println("// Copyright (c) 2024 Second Star Cavalier, LLC.");
        w.println("// GENERATED by stratum-codegen — do not edit.");
        w.println("// Source: vservice protos with option (spec.service_s2s) = {tag: \"stratum\"}");
        w.println();
        w.println("package " + pkg + ";");
        w.println();

        // Imports
        w.println("import " + TACPLUS_BASE + "." + SM_PREFIX + ".Handler;");
        w.println("import " + TACPLUS_BASE + ".types.services.stratum.Stratum;");
        for (VServiceDiscovery.HostedVService svc : services) {
            String wrapperPkg = TACPLUS_BASE + "." + SM_PREFIX +
                    ".internal.grpc.servers.vservices." + svc.protoPackage;
            w.println("import " + wrapperPkg + "." + svc.serviceName + ";");
        }
        w.println();

        w.println("/**");
        w.println(" * StratumVServiceBase wires tacplus-generated Handler interface methods");
        w.println(" * to stratum's vservice implementation providers.");
        w.println(" *");
        w.println(" * Discovered hosted vservices (tag: \"stratum\"):");
        for (VServiceDiscovery.HostedVService svc : services) {
            w.println(" *   - " + svc.protoPackage + "." + svc.serviceName +
                    " (" + svc.protoRelPath + ")");
        }
        w.println(" *");
        w.println(" * Extend this class and implement each provide*Handler() method.");
        w.println(" * When a new vservice is added with {tag: \"stratum\"}, this class");
        w.println(" * is regenerated automatically — no manual wiring needed.");
        w.println(" */");
        w.println("public abstract class StratumVServiceBase implements Handler {");
        w.println();

        for (VServiceDiscovery.HostedVService svc : services) {
            String handlerType = svc.serviceName + "." + svc.serviceName + "Handler";
            String getterName = "get" + svc.serviceName + "GrpcImpl";
            String providerName = "provide" + svc.serviceName + "Handler";
            String configHandlerName = "handle" + svc.serviceName + "Config";

            w.println("    // --- " + svc.serviceName + " (" + svc.protoPackage + ") ---");
            w.println();

            // getXxxGrpcImpl() implementation
            w.println("    @Override");
            w.println("    public final " + handlerType + " " + getterName + "() {");
            w.println("        return " + providerName + "();");
            w.println("    }");
            w.println();

            // handleXxxConfig() — vservices share stratum's config
            w.println("    @Override");
            w.println("    public void " + configHandlerName + "(Stratum.Config cfg) throws Exception {");
            w.println("        handleConfig(cfg);");
            w.println("    }");
            w.println();

            // Abstract provider method
            w.println("    /**");
            w.println("     * Returns the " + svc.serviceName + " handler implementation.");
            w.println("     * Called once at startup by the generated ServiceManager.");
            w.println("     */");
            w.println("    protected abstract " + handlerType + " " + providerName + "();");
            w.println();
        }

        // Abstract handleConfig — called by all vservice config handlers
        w.println("    /**");
        w.println("     * Called when stratum config is updated.");
        w.println("     * All hosted vservice config handlers delegate here.");
        w.println("     */");
        w.println("    protected abstract void handleConfig(Stratum.Config cfg) throws Exception;");
        w.println("}");
    }
}
