package com.gitlab.secondstarcavalier.controlplane.cavalier.services.stratum.codegen;

import java.io.IOException;
import java.io.PrintWriter;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/**
 * Generates StratumRecordMaps.java — the implementation of the generated
 * RecordMap service (the typed map plane). For every record type T (an EventBus
 * topic event the record store holds) it emits the five RecordMap RPC handlers:
 *
 *   new<T>Map      → create a working-set map (UUID id)
 *   add<T>ByKeys   → hydrate records from the typed hot store into the map
 *   merge<T>       → union two maps
 *   pull<T>        → the only data-returning op: typed records out of the map
 *   cleanup<T>     → drop the map
 *
 * All per-type knowledge lives here (generated); StratumHandler only returns an
 * instance via provideRecordMapHandler(), so the hand-written service names no
 * vservice — the same invariant EventStoreGenerator satisfies. Backed by the
 * generic WorkingSetStore (working-set maps) + the generated StratumEventStores
 * (typed hot IMaps).
 *
 * NOTE (Phase 3, increment 1): pull returns the whole map (paging fields on the
 * request are accepted but not yet honored); Filter/AddByQuery, AddBy{Graphdb,
 * Timedb} federation, and Modify are follow-on increments.
 */
public final class RecordMapImplGenerator {

    private static final String HOST_PKG =
            "com.gitlab.secondstarcavalier.controlplane.cavalier.services.stratum";
    private static final String MODEL_BASE = HOST_PKG + ".model";
    private static final String MODEL_TYPES_VSERVICES = MODEL_BASE + ".types.vservices";
    private static final String STRATUM_MSGS = MODEL_BASE + ".types.services.stratum.Stratum";
    private static final String RECORDMAP_IFACE =
            MODEL_BASE + ".s2sm.internal.grpc.servers.vservices.stratum.RecordMap";
    private static final String CALLER = MODEL_BASE + ".libs.servicemanager.Caller";
    private static final String PROTO_EXCEPTION = MODEL_BASE + ".types.libs.errors.ProtoException";
    private static final String CLASS_NAME = "StratumRecordMaps";

    private RecordMapImplGenerator() {}

    public static void generate(Path outputDir, List<EventTopicDiscovery.TopicEvent> records)
            throws IOException {
        Path pkgDir = outputDir.resolve(HOST_PKG.replace('.', '/'));
        Files.createDirectories(pkgDir);
        Path outFile = pkgDir.resolve(CLASS_NAME + ".java");
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(outFile))) {
            writeFile(w, records);
        }
    }

    private static void writeFile(PrintWriter w, List<EventTopicDiscovery.TopicEvent> records) {
        w.println("// Copyright (c) 2024 Second Star Cavalier, LLC.");
        w.println("// GENERATED by stratum-codegen — do not edit.");
        w.println("// Source: spec.record types (EventBus topic events the record store holds).");
        w.println();
        w.println("package " + HOST_PKG + ";");
        w.println();
        w.println("import java.util.UUID;");
        w.println("import java.util.function.Supplier;");
        w.println("import com.hazelcast.map.IMap;");
        w.println("import " + CALLER + ";");
        w.println("import " + PROTO_EXCEPTION + ";");
        w.println("import " + STRATUM_MSGS + ";");
        w.println("import " + RECORDMAP_IFACE + ";");
        w.println();
        w.println("/**");
        w.println(" * Typed map-plane implementation (RecordMap). One RPC family per record");
        w.println(" * type, backed by the generic WorkingSetStore + typed StratumEventStores.");
        w.println(" *");
        w.println(" * The stores are resolved per call via suppliers: StratumHandler rebuilds");
        w.println(" * them on every config update, so a captured reference would go stale.");
        w.println(" */");
        w.println("public final class " + CLASS_NAME + " implements RecordMap.RecordMapHandler {");
        w.println();
        w.println("    private final Supplier<WorkingSetStore> storeSupplier;");
        w.println("    private final Supplier<StratumEventStores> storesSupplier;");
        w.println();
        w.println("    public " + CLASS_NAME + "(Supplier<WorkingSetStore> storeSupplier,");
        w.println("                            Supplier<StratumEventStores> storesSupplier) {");
        w.println("        this.storeSupplier = storeSupplier;");
        w.println("        this.storesSupplier = storesSupplier;");
        w.println("    }");
        w.println();
        w.println("    private WorkingSetStore store() { return storeSupplier.get(); }");
        w.println("    private StratumEventStores stores() { return storesSupplier.get(); }");

        for (EventTopicDiscovery.TopicEvent e : records) {
            String t = e.eventType;                 // e.g. AgentEvent
            String fqn = fqn(e);                     // typed FQN for parse + cast
            String acc = field(e);                   // stores accessor, e.g. agentsensorAgentEvent

            // new<T>Map
            w.println();
            w.println("    @Override");
            w.println("    public Stratum.RecordMapHandle " + lower("New" + t + "Map")
                    + "(Caller caller, Stratum.New" + t + "MapRequest req) throws ProtoException {");
            w.println("        String mapId = UUID.randomUUID().toString();");
            w.println("        try {");
            w.println("            store().createMap(mapId);");
            w.println("        } catch (Exception ex) {");
            w.println("            throw new ProtoException(ProtoException.INTERNAL, ex.getMessage());");
            w.println("        }");
            w.println("        return Stratum.RecordMapHandle.newBuilder().setMapId(mapId).build();");
            w.println("    }");

            // add<T>ByKeys
            w.println();
            w.println("    @Override");
            w.println("    public Stratum.RecordMapStats " + lower("Add" + t + "ByKeys")
                    + "(Caller caller, Stratum.Add" + t + "ByKeysRequest req) throws ProtoException {");
            w.println("        long n = 0;");
            w.println("        for (String key : req.getKeysList()) {");
            w.println("            " + fqn + " ev = stores()." + acc + "().get(key);");
            w.println("            if (ev != null) {");
            w.println("                store().putEvent(req.getMapId(), key, ev.toByteArray());");
            w.println("                n++;");
            w.println("            }");
            w.println("        }");
            w.println("        return Stratum.RecordMapStats.newBuilder()");
            w.println("                .setMapId(req.getMapId()).setSize(n).build();");
            w.println("    }");

            // merge<T>
            w.println();
            w.println("    @Override");
            w.println("    public Stratum.RecordMapStats " + lower("Merge" + t)
                    + "(Caller caller, Stratum.Merge" + t + "Request req) throws ProtoException {");
            w.println("        long n;");
            w.println("        try {");
            w.println("            n = store().merge(req.getSourceMapId(), req.getTargetMapId());");
            w.println("        } catch (Exception ex) {");
            w.println("            throw new ProtoException(ProtoException.INTERNAL, ex.getMessage());");
            w.println("        }");
            w.println("        return Stratum.RecordMapStats.newBuilder()");
            w.println("                .setMapId(req.getTargetMapId()).setSize(n).build();");
            w.println("    }");

            // pull<T> — the only data-returning op
            w.println();
            w.println("    @Override");
            w.println("    public Stratum.Pull" + t + "Response " + lower("Pull" + t)
                    + "(Caller caller, Stratum.Pull" + t + "Request req) throws ProtoException {");
            w.println("        Stratum.Pull" + t + "Response.Builder out = Stratum.Pull" + t + "Response.newBuilder();");
            w.println("        try {");
            w.println("            IMap<String, byte[]> ws = store().getWorkingSetMap(req.getMapId());");
            w.println("            for (byte[] raw : ws.values()) {");
            w.println("                out.addItems(" + fqn + ".parseFrom(raw));");
            w.println("            }");
            w.println("        } catch (Exception ex) {");
            w.println("            throw new ProtoException(ProtoException.INTERNAL, ex.getMessage());");
            w.println("        }");
            w.println("        return out.build();");
            w.println("    }");

            // cleanup<T>
            w.println();
            w.println("    @Override");
            w.println("    public Stratum.RecordMapStats " + lower("Cleanup" + t)
                    + "(Caller caller, Stratum.RecordMapHandle req) throws ProtoException {");
            w.println("        try {");
            w.println("            store().deleteMap(req.getMapId());");
            w.println("        } catch (Exception ex) {");
            w.println("            throw new ProtoException(ProtoException.INTERNAL, ex.getMessage());");
            w.println("        }");
            w.println("        return Stratum.RecordMapStats.newBuilder()");
            w.println("                .setMapId(req.getMapId()).setSize(0).build();");
            w.println("    }");
        }

        w.println("}");
    }

    // ----- naming helpers (mirror EventStoreGenerator) -----

    private static String fqn(EventTopicDiscovery.TopicEvent e) {
        return MODEL_TYPES_VSERVICES + "." + e.protoPackage + "." + outerClass(e.protoPackage) + "." + e.eventType;
    }

    private static String field(EventTopicDiscovery.TopicEvent e) {
        return e.protoPackage + e.eventType;
    }

    private static String outerClass(String protoPackage) {
        return Character.toUpperCase(protoPackage.charAt(0)) + protoPackage.substring(1);
    }

    /** Lowercase the first character (RPC name -> Java method name). */
    private static String lower(String s) {
        return Character.toLowerCase(s.charAt(0)) + s.substring(1);
    }
}
