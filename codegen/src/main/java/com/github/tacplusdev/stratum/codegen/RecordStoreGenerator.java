package com.github.tacplusdev.stratum.codegen;

import java.io.IOException;
import java.io.PrintWriter;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;

/**
 * Generates the per-record-type knowledge the store needs, so the hand-written
 * store ({@code com.github.tacplusdev.stratum.store}) never names a record type:
 *
 * <ul>
 *   <li>{@code StratumStores} — one typed {@code IMap<String, T>} per record type,
 *       which the generated query plane scans.</li>
 *   <li>{@code StratumRecordTypes} — the store's {@code RecordTypes}: each type's
 *       name, durability ({@code (spec.record).durability}), key and namespace
 *       accessors, and the decoding of a write surface {@code RecordOp} into a
 *       {@code WriteOp}.</li>
 * </ul>
 */
public final class RecordStoreGenerator {

    static final String HOST_PKG = "com.github.tacplusdev.stratum";
    static final String STORES_CLASS = "StratumStores";
    static final String TYPES_CLASS = "StratumRecordTypes";
    private static final String MODEL_BASE = HOST_PKG + ".model";
    private static final String QUERY = MODEL_BASE + ".types.vservices.query.Query";

    private RecordStoreGenerator() {}

    public static void generate(Path outputDir, List<RecordDiscovery.RecordDecl> records)
            throws IOException {
        Path pkgDir = outputDir.resolve(HOST_PKG.replace('.', '/'));
        Files.createDirectories(pkgDir);
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(pkgDir.resolve(STORES_CLASS + ".java")))) {
            writeStores(w, records);
        }
        try (PrintWriter w = new PrintWriter(Files.newBufferedWriter(pkgDir.resolve(TYPES_CLASS + ".java")))) {
            writeTypes(w, records);
        }
    }

    private static void header(PrintWriter w) {
        w.println("// Copyright (c) 2026 Jody Scott");
        w.println("// SPDX-License-Identifier: Apache-2.0");
        w.println("// GENERATED by stratum-codegen — do not edit.");
        w.println("// Source: the (spec.record) messages of the generation.");
        w.println();
        w.println("package " + HOST_PKG + ";");
        w.println();
    }

    private static void writeStores(PrintWriter w, List<RecordDiscovery.RecordDecl> records) {
        header(w);
        w.println("import com.hazelcast.core.HazelcastInstance;");
        w.println("import com.hazelcast.map.IMap;");
        w.println();
        w.println("/**");
        w.println(" * The record maps, typed: one IMap per record type, keyed by the record key");
        w.println(" * (an integer key in decimal). Read-only to everything but the store's write");
        w.println(" * path (com.github.tacplusdev.stratum.store.RecordStore), which writes the same");
        w.println(" * maps by name once the redo service has acked each write.");
        w.println(" */");
        w.println("public final class " + STORES_CLASS + " {");
        w.println();
        for (RecordDiscovery.RecordDecl r : records) {
            w.println("    private final IMap<String, " + fqn(r) + "> " + field(r) + ";");
        }
        w.println();
        w.println("    public " + STORES_CLASS + "(HazelcastInstance hz) {");
        for (RecordDiscovery.RecordDecl r : records) {
            w.println("        " + field(r) + " = hz.getMap(\"" + r.fullName() + "\");");
        }
        w.println("    }");
        for (RecordDiscovery.RecordDecl r : records) {
            w.println();
            w.println("    public IMap<String, " + fqn(r) + "> " + field(r) + "() { return " + field(r) + "; }");
        }
        w.println("}");
    }

    private static void writeTypes(PrintWriter w, List<RecordDiscovery.RecordDecl> records) throws IOException {
        header(w);
        w.println("import java.util.List;");
        w.println();
        w.println("import com.google.protobuf.Descriptors;");
        w.println("import com.google.protobuf.Message;");
        w.println();
        w.println("import " + HOST_PKG + ".store.RecordType;");
        w.println("import " + HOST_PKG + ".store.RecordTypes;");
        w.println("import " + HOST_PKG + ".store.WriteOp;");
        w.println("import " + MODEL_BASE + ".types.sys.errors.ProtoException;");
        w.println("import " + MODEL_BASE + ".types.sys.redolog.RedoOuterClass.RedoKey;");
        w.println("import " + MODEL_BASE + ".types.sys.spec.Spec.Durability;");
        w.println("import " + QUERY + ";");
        w.println();
        w.println("/**");
        w.println(" * Every record type the store holds, as the write path sees it.");
        w.println(" *");
        w.println(" * A RecordOp is decoded by the name of the request message its oneof carries");
        w.println(" * (Put<T>Request, InsertIfAbsent<T>Request, ...), which tacplus fixes, rather");
        w.println(" * than by the oneof's field names, which it derives.");
        w.println(" */");
        w.println("public final class " + TYPES_CLASS + " implements RecordTypes {");
        w.println();
        for (RecordDiscovery.RecordDecl r : records) {
            if (r.storeNamespaceField.isEmpty()) {
                throw new IOException(r.fullName() + " declares (spec.record) but no (spec.store_namespace)"
                        + " field; the store cannot hold a row to a tenant it cannot read off the row");
            }
            String cast = "((" + fqn(r) + ") m)";
            w.println("    /** " + r.fullName() + ", acked at " + r.durability + ". */");
            w.println("    public static final RecordType " + constant(r) + " = new RecordType(");
            w.println("            \"" + r.fullName() + "\", Durability." + r.durability + ", " + fqn(r) + ".parser(),");
            w.println("            m -> " + keyOf(r, cast + ".get" + pascal(r.recordKey) + "()") + ",");
            w.println("            m -> " + cast + ".get" + pascal(r.storeNamespaceField) + "());");
            w.println();
        }
        w.print("    private static final List<RecordType> ALL = List.of(");
        for (int i = 0; i < records.size(); i++) {
            w.print((i == 0 ? "" : ", ") + constant(records.get(i)));
        }
        w.println(");");
        w.println();
        w.println("    @Override");
        w.println("    public List<RecordType> all() { return ALL; }");
        w.println();
        w.println("    @Override");
        w.println("    public RecordType byName(String fullName) {");
        w.println("        switch (fullName) {");
        for (RecordDiscovery.RecordDecl r : records) {
            w.println("            case \"" + r.fullName() + "\": return " + constant(r) + ";");
        }
        w.println("            default: return null;");
        w.println("        }");
        w.println("    }");
        w.println();
        w.println("    /** Every record map's name, which is its record type's full name. */");
        w.println("    public static List<String> mapNames() {");
        w.print("        return List.of(");
        for (int i = 0; i < records.size(); i++) {
            w.print((i == 0 ? "" : ", ") + "\"" + records.get(i).fullName() + "\"");
        }
        w.println(");");
        w.println("    }");
        w.println();
        w.println("    /** The default instance of the record type with this full name, or null. */");
        w.println("    public static Message defaultInstance(String fullName) {");
        w.println("        switch (fullName) {");
        for (RecordDiscovery.RecordDecl r : records) {
            w.println("            case \"" + r.fullName() + "\": return " + fqn(r) + ".getDefaultInstance();");
        }
        w.println("            default: return null;");
        w.println("        }");
        w.println("    }");
        w.println();
        w.println("    @Override");
        w.println("    public WriteOp decode(Query.RecordOp op) throws ProtoException {");
        w.println("        Descriptors.FieldDescriptor set = op.getOneofFieldDescriptor(");
        w.println("                Query.RecordOp.getDescriptor().getOneofs().get(0));");
        w.println("        if (set == null) {");
        w.println("            throw new ProtoException(ProtoException.INVALID_ARGUMENT, \"a RecordOp carries no write\");");
        w.println("        }");
        w.println("        Message req = (Message) op.getField(set);");
        w.println("        switch (req.getDescriptorForType().getName()) {");
        for (RecordDiscovery.RecordDecl r : records) {
            String t = r.typeName;
            String c = constant(r);
            w.println("            case \"Put" + t + "Request\": {");
            w.println("                Query.Put" + t + "Request r = (Query.Put" + t + "Request) req;");
            w.println("                return WriteOp.put(" + c + ", r.getItem(), durability(r.getDurabilityValue()));");
            w.println("            }");
            w.println("            case \"InsertIfAbsent" + t + "Request\": {");
            w.println("                Query.InsertIfAbsent" + t + "Request r = (Query.InsertIfAbsent" + t + "Request) req;");
            w.println("                return WriteOp.insertIfAbsent(" + c + ", r.getItem(), durability(r.getDurabilityValue()));");
            w.println("            }");
            w.println("            case \"ReplaceIfUnchanged" + t + "Request\": {");
            w.println("                Query.ReplaceIfUnchanged" + t + "Request r = (Query.ReplaceIfUnchanged" + t + "Request) req;");
            w.println("                if (r.hasExpectedRevision()) {");
            w.println("                    return WriteOp.replaceIfRevision(" + c + ", r.getItem(), r.getExpectedRevision(),");
            w.println("                            durability(r.getDurabilityValue()));");
            w.println("                }");
            w.println("                if (r.hasExpectedItem()) {");
            w.println("                    return WriteOp.replaceIfItem(" + c + ", r.getItem(), r.getExpectedItem(),");
            w.println("                            durability(r.getDurabilityValue()));");
            w.println("                }");
            w.println("                throw new ProtoException(ProtoException.INVALID_ARGUMENT,");
            w.println("                        \"ReplaceIfUnchanged" + t + " names neither an expected revision nor an expected item\");");
            w.println("            }");
            w.println("            case \"Delete" + t + "Request\": {");
            w.println("                Query.Delete" + t + "Request r = (Query.Delete" + t + "Request) req;");
            w.println("                return WriteOp.delete(" + c + ", " + keyOf(r, "r.get" + pascal(r.recordKey) + "()") + ",");
            w.println("                        r.get" + pascal(r.storeNamespaceField) + "(), durability(r.getDurabilityValue()));");
            w.println("            }");
        }
        w.println("            default:");
        w.println("                throw new ProtoException(ProtoException.INVALID_ARGUMENT,");
        w.println("                        \"a RecordOp carries \" + req.getDescriptorForType().getName()");
        w.println("                                + \", which is no write this store holds\");");
        w.println("        }");
        w.println("    }");
        w.println();
        w.println("    /** A request's durability; UNSPECIFIED (the type's own level) when unknown. */");
        w.println("    private static Durability durability(int value) {");
        w.println("        Durability d = Durability.forNumber(value);");
        w.println("        return d == null ? Durability.DURABILITY_UNSPECIFIED : d;");
        w.println("    }");
        for (RecordDiscovery.RecordDecl r : records) {
            String keyJava = r.stringKey() ? "String" : (isUnsigned32(r.keyProtoType) || is32(r.keyProtoType) ? "int" : "long");
            w.println();
            w.println("    /** The redo key of the " + r.fullName() + " entry with this " + r.recordKey + ". */");
            w.println("    public static RedoKey " + lower(r.typeName) + "Key(" + keyJava + " key) {");
            w.println("        return " + keyOf(r, "key") + ";");
            w.println("    }");
        }
        w.println("}");
    }

    /** A Java expression building the RedoKey of a key value expression. */
    private static String keyOf(RecordDiscovery.RecordDecl r, String value) {
        String t = r.keyProtoType;
        if (r.stringKey()) {
            return "RedoKey.newBuilder().setStringKey(" + value + ").build()";
        }
        if (isUnsigned32(t)) {
            return "RedoKey.newBuilder().setUintKey(Integer.toUnsignedLong(" + value + ")).build()";
        }
        if (t.startsWith("uint") || t.startsWith("fixed")) {
            return "RedoKey.newBuilder().setUintKey(" + value + ").build()";
        }
        return "RedoKey.newBuilder().setIntKey(" + value + ").build()";
    }

    private static boolean isUnsigned32(String t) {
        return t.equals("uint32") || t.equals("fixed32");
    }

    private static boolean is32(String t) {
        return t.equals("int32") || t.equals("sint32") || t.equals("sfixed32");
    }

    /** UPPER_SNAKE constant for a record type, e.g. LETSENCRYPT_LETS_ENCRYPT_CERT. */
    static String constant(RecordDiscovery.RecordDecl r) {
        StringBuilder b = new StringBuilder(r.protoPackage.toUpperCase().replace('.', '_')).append('_');
        String t = r.typeName;
        for (int i = 0; i < t.length(); i++) {
            char c = t.charAt(i);
            if (i > 0 && Character.isUpperCase(c) && Character.isLowerCase(t.charAt(i - 1))) {
                b.append('_');
            }
            b.append(Character.toUpperCase(c));
        }
        return b.toString();
    }

    /** The typed record's Java FQN. */
    static String fqn(RecordDiscovery.RecordDecl r) {
        return r.javaPackage + "." + r.outerClassName + "." + r.typeName;
    }

    /** The typed map accessor's name, e.g. letsencryptLetsEncryptCert. */
    static String field(RecordDiscovery.RecordDecl r) {
        return r.protoPackage.replace(".", "") + r.typeName;
    }

    /** snake_case proto field -> PascalCase getter stem (spiffe_id -> SpiffeId). */
    static String pascal(String snake) {
        StringBuilder b = new StringBuilder();
        boolean up = true;
        for (char c : snake.toCharArray()) {
            if (c == '_') { up = true; continue; }
            b.append(up ? Character.toUpperCase(c) : c);
            up = false;
        }
        return b.toString();
    }

    static String lower(String s) {
        return Character.toLowerCase(s.charAt(0)) + s.substring(1);
    }
}
